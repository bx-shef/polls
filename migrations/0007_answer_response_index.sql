-- Индекс под чтение ответов по записи (#49).
--
-- ⚠️ Повод конкретный: SQL-агрегация дашборда соединяет `response_answer` с `response`, а FK-колонка
-- `response_id` индекса не имела — Postgres под внешний ключ его не создаёт. `EXPLAIN` на срезе
-- показывал `Seq Scan on response_answer`, то есть ПОЛНЫЙ скан таблицы ВСЕХ арендаторов, и четыре
-- раза на одно открытие дашборда (по одному на измерение). Это ровно тот кросс-тенантный эффект,
-- ради устранения которого #49 и открыт: он не исчез, а переехал с event loop в базу.
--
-- ⚠️ Составной, а не голый `response_id`: запросы среза считают метрики через
-- `filter (where ra.question_key = ...)`, и вторая колонка закрывает этот фильтр индексом же.
-- Той же парой пользуется `hydrate` при чтении списка ответов.
--
-- ⚠️ Прежний `idx_answer_question (question_key)` НЕ заменяет: ключи вопросов у всех порталов
-- одинаковы (`q_nps`, `q_csat`, `q_liked` приезжают с демо-опросом при установке), поэтому вход по
-- нему собирает ответы всех арендаторов и только потом отсекает по `portal_id`.
create index if not exists idx_answer_response on response_answer (response_id, question_key);
