import { bodyLimitStatus, CONTENT_LENGTH_HEADER, TRANSFER_ENCODING_HEADER } from '~core/api/body-limit'

/**
 * Общий потолок размера тела — ДО маршрутизации, на каждый запрос.
 *
 * Почему middleware, а не проверка в роутах (она там тоже есть, и остаётся). Поимённые капы защищают
 * ровно те роуты, где автор о них вспомнил; забытый роут выглядит точно так же, как защищённый, и
 * тишина в логах ничем не отличается. Здесь проверка стоит перед маршрутизацией, поэтому новый роут
 * получает её сам, ничего для этого не делая, — а публичные вебхуки Bitrix24, которые буферизовали
 * тело `readBody` **до** сверки токена, перестают быть каналом OOM.
 *
 * ⚠️ Middleware не видит статику (обработчик публичных файлов Nitro регистрируется раньше — это
 * подробно разобрано в `server/plugins/security-headers.ts`). Здесь это неважно: у GET за статикой
 * тела нет, а проверять нечего.
 *
 * ⚠️ **Осознанное исключение из инварианта «вебхук всегда отвечает 200»** (`/api/b24/install`,
 * `/api/b24/deal-update`, `/api/b24/robot`). Инвариант существует, чтобы не раскрывать анонимному
 * вызывающему, установлен ли портал и верен ли токен. Отказ здесь принимается по одному заголовку,
 * до единого обращения к хранилищу, поэтому оракулом не служит: он одинаков для настоящего портала и
 * для случайного сканера. Сохранить 200 без чтения тела всё равно невозможно — а прочитать его и
 * значит согласиться на то, от чего защищаемся.
 *
 * Возврат значения из middleware ЗАВЕРШАЕТ запрос (h3 пишет тело и выходит из цепочки слоёв);
 * `undefined` — пропускает дальше.
 */
export default defineEventHandler((event) => {
  const verdict = bodyLimitStatus({
    // `getRequestHeader` склеивает повторы заголовка через запятую. Для `Content-Length` это как раз
    // нужное поведение: склейка `10, 20` не пройдёт разбор и даст 411 — то есть отказ, а не догадку,
    // какой из двух заявленных размеров настоящий.
    contentLength: getRequestHeader(event, CONTENT_LENGTH_HEADER),
    transferEncoding: getRequestHeader(event, TRANSFER_ENCODING_HEADER)
  })
  if (!verdict) return

  setResponseStatus(event, verdict.status)
  return { ok: false, error: verdict.error }
})
