/**
 * Обезвреживание недоверенного текста, который увидит человек.
 *
 * Живёт отдельным модулем, потому что таких мест уже два и они друг другу не родня: отзыв сотрудника
 * (уезжает в issue трекера) и текст ошибки, пришедший по сети (показывается на странице опроса).
 * Правило у них общее — символ, который умеет переставить текст или спрятать его от читателя, до
 * читателя доходить не должен.
 */

/**
 * Враждебные и невидимые символы. Записаны escape-последовательностями НАМЕРЕННО: литералы здесь сами
 * были бы Trojan-Source-атакой на того, кто читает этот файл (и ломали бы git — он считает такой файл
 * бинарным). Убираем: управляющие C0 (кроме таба и переводов строк), переопределения направления
 * текста (U+202A–U+202E, U+2066–U+2069, U+061C), нулевой ширины, метки направления и BOM
 * (U+200B–U+200F, U+FEFF), невидимые операторы (U+2060–U+2064), разделители строк и абзацев
 * (U+2028/U+2029), «теговый» блок U+E0000–U+E007F (им записывается целый скрытый текст).
 */
// eslint-disable-next-line no-control-regex
const HOSTILE_CHARS = /[\x00-\x08\x0b\x0c\x0e-\x1f\x7f\u00ad\u034f\u061c\u180e\u200b-\u200f\u2028-\u2029\u202a-\u202e\u2060-\u2064\u2066-\u2069\ufff9-\ufffb\ufeff\u{e0000}-\u{e007f}]/gu

/**
 * Убрать управляющие, направляющие и невидимые символы. Табы и переводы строк ОСТАВЛЯЕТ намеренно —
 * в многострочном тексте (комментарий к отзыву) они законны. Там, где текст обязан быть однострочным,
 * зовите {@link toSingleLine}.
 */
export function stripHostileChars(input: unknown): string {
  return String(input ?? '').replace(HOSTILE_CHARS, '')
}

/**
 * То же плюс схлопывание пробельных пропусков в один пробел и обрезка по краям — для мест, где текст
 * рисуется ОДНОЙ строкой (заголовок алерта, строка контекста в issue). Без этого перевод строки внутри
 * значения вырывает его из своей строки и дописывает в разметку лишнее.
 */
export function toSingleLine(input: unknown): string {
  return stripHostileChars(input).replace(/\s+/g, ' ').trim()
}
