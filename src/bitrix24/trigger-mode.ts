/**
 * Режим авто-триггера: каким путём опрос запускается при доходе сделки до стадии.
 *
 * Путей два, и **включить оба одновременно нельзя**: робот вызывается на входе в стадию, а событие
 * `ONCRMDEALUPDATE` приходит тем же изменением — история подтвердит свежий переход, и клиент получит
 * ДВА приглашения на один переход. Поэтому режим — единственный источник правды: он решает и что
 * регистрировать при установке, и какой входящий роут обслуживать.
 *
 * - `event` (дефолт) — только `event.bind ONCRMDEALUPDATE` + подтверждение перехода историей стадий.
 *   Работает на всех тарифах.
 * - `robot` — только робот автоматизации: точная семантика «вошла в стадию», но нужен тариф с роботами.
 *
 * ⚠️ **Значения `both` больше нет, и это решение, а не упрощение** (снято вместе с #175). Полезного
 * состояния у него не было ни одного: вне триггер-стадии робот не создаёт ничего вовсе
 * (`surveysTriggeredBy` вернёт пусто), то есть `both` тождественен `event`; на триггер-стадии — дубль.
 * Пока робот выписывал только токен, дубль был невидимым мусором в базе; с #175 обе ветки создают
 * НАСТОЯЩЕЕ дело в таймлайне, и ключи перехода у них разные по построению (`ID` записи истории против
 * момента срабатывания) — склеить их дедупу нечем. Одна переменная окружения, набранная по логике
 * «оба надёжнее», давала бы клиенту два письма и двойной счёт в аналитике. Настройки, у которой нет
 * собственного полезного состояния, быть не должно.
 *
 * ⚠️ Портал, где в окружении осталось `both`, получит дефолт `event` (`resolveTriggerMode` не узнаёт
 * значение), а `pnpm env:check` назовёт переменную и перечислит допустимые — то есть безопасный путь
 * плюс явное сообщение оператору, а не тихое переключение.
 *
 * Сейчас режим читается из окружения; когда появится страница настроек портала, она будет питать
 * тот же резолвер — контракт (`resolveTriggerMode`) не изменится.
 */

export const TRIGGER_MODES = ['event', 'robot'] as const
export type TriggerMode = (typeof TRIGGER_MODES)[number]

export const TRIGGER_MODE_DEFAULT: TriggerMode = 'event'

/** Разбор значения из настроек/окружения; мусор/пусто → дефолт (`event` — работает на всех тарифах). */
export function resolveTriggerMode(raw: unknown): TriggerMode {
  const v = typeof raw === 'string' ? raw.trim().toLowerCase() : ''
  return (TRIGGER_MODES as readonly string[]).includes(v) ? (v as TriggerMode) : TRIGGER_MODE_DEFAULT
}

/**
 * Обслуживать ли входящее событие `ONCRMDEALUPDATE` (и регистрировать `event.bind` при установке).
 *
 * ⚠️ Предикаты остались функциями, хотя режимов два и `mode === 'event'` читалось бы так же. Смысл в
 * том, что вызывающие (роут события, роут робота, `integrationCalls`) спрашивают про СПОСОБНОСТЬ, а не
 * сравнивают со строкой: появится третий путь (лид/смарт-процесс) — правка будет здесь, а не в пяти
 * местах, каждое из которых молча пропустит новый режим.
 */
export function eventTriggerEnabled(mode: TriggerMode): boolean {
  return mode === 'event'
}

/** Обслуживать ли вызов робота (и регистрировать `bizproc.robot.add` при установке). */
export function robotTriggerEnabled(mode: TriggerMode): boolean {
  return mode === 'robot'
}
