/**
 * The survey template as the whole application understands it.
 *
 * Одна модель на всех: её строит адаптер импорта, её рендерит публичная страница, по ней же
 * пересчитываются баллы. Разводить «формат импорта» и «формат показа» значило бы завести
 * два словаря на одну вещь и мапперы между ними — а расходиться они начали бы с первой правки.
 *
 * Модель описана в `docs/PROCESS.md`, раздел 7. Здесь только типы: ни базы, ни сети, ни REST.
 */

/** Тип вопроса. Осей две, и они независимы: виджет и метрика. */
export type SurveyQuestionType = 'scale' | 'text' | 'date'

/** Диапазон интерпретации: границы включительно и текст, который увидит респондент. */
export interface SurveyBand {
  from: number
  to: number
  /** Уже вычищенный от HTML текст. Разметку мы не храним — см. `docs/PROCESS.md`, раздел 7. */
  text: string
}

export interface SurveyQuestion {
  /**
   * Ключ вопроса внутри версии шаблона. Уникален — это инвариант проекта.
   *
   * Обычно совпадает с кодом `UF_*` источника. Расходится в одном случае: вопрос стоял
   * в двух секциях сразу, и второе вхождение получило суффикс секции.
   */
  key: string
  /**
   * Код поля в источнике, по которому берётся значение ответа.
   *
   * ⚠ При расщеплении два разных `key` указывают на ОДИН `sourceKey`, и обоим при пересчёте
   * отдаётся одно значение — только так баллы сходятся с историческими.
   */
  sourceKey: string
  /** Формулировка. В источнике её нет в конфигурации — она лежит подписями полей. */
  title: string
  type: SurveyQuestionType
  /** Вес внутри секции, из `SETTING.SIZE`. */
  weight: number
  /** Идёт ли вопрос в оценку. Вес `0` в источнике означал именно это. */
  scored: boolean
  /** Границы шкалы — только у балльных вопросов. */
  scale?: { min: number, max: number }
}

export interface SurveySection {
  /** Ключ секции: `product`, `process`, `personal`, `open`. */
  key: string
  title: string
  /**
   * Даёт ли секция балл.
   *
   * В источнике признаком было непустое `FIELD` — имя свойства карточки, куда писался балл
   * секции. Пустое `FIELD` — секция открытых вопросов, балла у неё нет.
   */
  scored: boolean
  questions: SurveyQuestion[]
  bands: SurveyBand[]
}

export interface SurveyTemplate {
  /** Код опроса: `brand`, `game`, `digital`, … Он же часть внешнего ключа идемпотентности. */
  code: string
  title: string
  sections: SurveySection[]
}
