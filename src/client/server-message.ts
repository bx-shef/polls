/**
 * Извлечение текста ошибки, который прислал НАШ сервер.
 *
 * Зачем это в ядре, а не в композабле страницы: причину отказа знает только сервер — «эта ссылка
 * уже использована», «срок ссылки истёк — попросите новую у менеджера», «страница устарела».
 * Все такие строки написаны в одном месте (`src/api/handlers.ts`) и приходят в теле как
 * `{ ok: false, error }`. Клиент раньше их выбрасывал (`catch {}`) и показывал своё «проверьте
 * соединение» — то есть респондент с истёкшей ссылкой чинил интернет вместо того, чтобы попросить
 * новую. Поэтому источник пользовательского текста ровно один — сервер, а клиентская строка нужна
 * только там, где ответа нет вовсе (обрыв сети, страница прокси).
 *
 * Функция чистая и не зависит от Vue/Nuxt: разбирает форму ошибки `$fetch`/`useAsyncData`
 * (`FetchError.data` / `NuxtError.data`), поэтому проверяется обычным юнит-тестом.
 */

/**
 * Предел длины принимаемого текста. Между нами и браузером может стоять прокси или CDN, и его
 * страница ошибки (HTML целиком) не должна оказаться в интерфейсе респондента вместо сообщения.
 * Наши строки заметно короче: самая длинная — про истёкшую ссылку, около 90 символов.
 */
export const MAX_SERVER_MESSAGE = 300

/**
 * Текст ошибки от сервера либо `undefined`, если пришло не наше тело (обрыв сети, чужой формат,
 * пустая строка, подозрительно длинный блоб). Вызывающий подставляет свой фолбэк.
 */
export function serverMessage(err: unknown): string | undefined {
  const raw = (err as { data?: { error?: unknown } } | null | undefined)?.data?.error
  if (typeof raw !== 'string') return undefined
  const text = raw.trim()
  return text && text.length <= MAX_SERVER_MESSAGE ? text : undefined
}
