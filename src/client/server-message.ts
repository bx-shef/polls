/**
 * Извлечение текста ошибки, который прислал НАШ сервер.
 *
 * Зачем это в ядре, а не в композабле страницы: причину отказа знает только сервер — «эта ссылка уже
 * использована», «срок ссылки истёк — попросите новую у менеджера», «страница устарела». Клиент видит
 * лишь факт неуспеха, и раньше подменял причину своим «проверьте соединение» — то есть респондент с
 * истёкшей ссылкой чинил интернет вместо того, чтобы попросить новую. Поэтому текст пишет сервер, а
 * клиентская строка нужна только там, где ответа нет вовсе (обрыв сети, страница прокси).
 *
 * ⚠️ Текстов у сервера НЕ одно место: контур A отвечает из ядра (`src/api/handlers.ts`), а дашборд,
 * админка, виджеты и вебхуки — из своих роутов `server/api/**`. Общий у них контракт, а не файл:
 * тело ответа `{ ok: false, error: '<строка для человека>' }`. Эта функция знает только контракт.
 *
 * ⚠️ Инвариант, на котором всё держится: строки в теле — **литералы**, без подстановки пользовательского
 * ввода. Иначе отправитель запроса напишет текст, который мы покажем на своей странице под своим
 * брендом (готовая площадка для фишинга), и никакое экранирование от этого не спасает — оно защищает
 * от разметки, а не от смысла. Инвариант проверяется тестом (`test/server-message.test.ts`).
 *
 * Функция чистая и не зависит от Vue/Nuxt: разбирает форму ошибки `$fetch`/`useAsyncData`, поэтому
 * проверяется обычным юнит-тестом.
 */
import { toSingleLine } from '../domain/text'

/**
 * Предел длины принимаемого текста — последний рубеж на случай, если тело перестало быть нашим.
 *
 * ⚠️ Запас тут МАЛЕНЬКИЙ, и это надо знать при правке текстов: самая длинная строка контура A — 78
 * символов, но самая длинная вообще, {@link ADMIN_REQUIRED_MESSAGE} (объяснение продавцу, что его
 * правки не потеряны), — уже 288. Ещё одно предложение — и самое важное сообщение проекта молча
 * схлопнется в фолбэк. Поэтому предел проверяется тестом по ВСЕМ серверным текстам, а не на глаз.
 */
export const MAX_SERVER_MESSAGE = 300

/**
 * Текст ошибки от сервера либо `undefined`, если пришло не наше тело (обрыв сети, чужой формат, пустая
 * строка, подозрительно длинный блоб). Вызывающий подставляет свой фолбэк.
 *
 * Две формы тела читаются обе: роут, отвечающий по конвенции проекта (`setResponseStatus` + `return
 * { ok:false, error }`), кладёт текст в `data.error`, а брошенный где-то выше `createError({ data })`
 * Nitro заворачивает в свой конверт — тогда текст уезжает в `data.data.error`. Читать только первую
 * форму значит иногда показывать человеку служебное значение.
 *
 * Текст санируется, хотя пишем его мы: невидимые и переставляющие символы (Trojan Source) убиваются,
 * а перевод строки схлопывается — заголовок алерта однострочный. Это защита в глубину на случай, когда
 * тело перестало быть нашим (промежуточный прокси, отдающий JSON с полем `error`).
 */
export function serverMessage(err: unknown): string | undefined {
  const outer = (err as { data?: Envelope } | null | undefined)?.data
  const body = typeof outer?.error === 'string' ? outer : outer?.data
  // Сверяем весь конверт, а не только поле: `{ ok:false, error }` — наш контракт, и шлюз, ответивший
  // коротким `{"error":"upstream timeout"}`, иначе показал бы респонденту это по-английски.
  // (HTML-страницу прокси отсекает не длина, а то, что `data` окажется строкой, а не объектом.)
  if (body?.ok !== false || typeof body.error !== 'string') return undefined
  const text = toSingleLine(body.error)
  return text && text.length <= MAX_SERVER_MESSAGE ? text : undefined
}

/** Тело ответа по конвенции проекта; `data` — та же форма во втором конверте Nitro. */
interface Envelope {
  ok?: unknown
  error?: unknown
  data?: { ok?: unknown; error?: unknown }
}
