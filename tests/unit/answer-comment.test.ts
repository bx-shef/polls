import { describe, expect, it } from 'vitest'
import { buildAnswerComment } from '../../server/domain/answers/comment'
import type { SurveyTemplate } from '../../server/domain/surveys/model'
import { scoreSurvey } from '../../server/domain/surveys/scoring'

/**
 * Комментарий в таймлайне — то, ради чего весь путь и затевался: менеджер открывает сделку
 * и видит, что ответил клиент. Здесь держится главное требование раздела 6 `docs/PROCESS.md`
 * — текст **не обрезается** — и то, что в комментарий не уезжает разметка, собранная
 * из набранного посторонним человеком.
 */

const TEMPLATE: SurveyTemplate = {
  code: 'brand',
  title: 'Оценка работы по проекту',
  sections: [
    {
      key: 'product',
      title: 'Продукт',
      scored: true,
      bands: [{ from: 8, to: 10, text: 'Мы на вершине!' }],
      questions: [
        { key: 'P1', sourceKey: 'P1', title: 'Качество результата', type: 'scale', weight: 60, scored: true, scale: { min: 0, max: 10 } },
        { key: 'P2', sourceKey: 'P2', title: 'Соответствие задаче', type: 'scale', weight: 40, scored: true, scale: { min: 0, max: 10 } },
      ],
    },
    {
      key: 'open',
      title: 'Открытые вопросы',
      scored: false,
      bands: [],
      questions: [
        { key: 'T1', sourceKey: 'T1', title: 'Что понравилось', type: 'text', weight: 0, scored: false },
        { key: 'T2', sourceKey: 'T2', title: 'Что улучшить', type: 'text', weight: 0, scored: false },
      ],
    },
  ],
}

function comment(answers: Record<string, number | string | null>) {
  return buildAnswerComment(TEMPLATE, answers, scoreSurvey(TEMPLATE, answers))
}

describe('комментарий в таймлайн', () => {
  it('не обрезает текст ответа', () => {
    // Требование раздела 6, и оно не про аккуратность: развёрнутый ответ и есть самое
    // ценное, что приносит опрос. Обрезав его до превью, мы оставим менеджеру ровно ту
    // бесполезную среднюю цифру, против которой написан весь проект.
    const long = 'Очень довольны. '.repeat(200)
    const body = comment({ P1: 9, P2: 8, T1: long, T2: null })

    expect(body).toContain(long)
  })

  it('показывает балл секции', () => {
    const body = comment({ P1: 9, P2: 8, T1: null, T2: null })

    // 9×0.6 + 8×0.4 = 8.6
    expect(body).toContain('Продукт: 8,6')
  })

  it('показывает балл КАЖДОГО вопроса, а не только средний', () => {
    // ⚠ Гвард под замечание владельца: «у нас 2 вопроса и 1 комментарий — в деле такого
    // не видно». Первая редакция печатала один агрегат, и менеджер видел «Продукт: 8,6»,
    // не зная, что за ним 9 и 8. Идти ради этого в поле «Ответы (JSON)» — не работа человека.
    const body = comment({ P1: 9, P2: 8, T1: null, T2: null })

    expect(body).toContain('9')
    expect(body).toContain('8')
    expect(body.split('\n').some(line => line.includes('9 из'))).toBe(true)
  })

  it('НЕ показывает текст диапазона — он написан для клиента, не для менеджера', () => {
    // ⚠ Гвард под замечание владельца: «откуда „Спасибо! Рады, что всё получилось“».
    // Это фраза, которую видит РЕСПОНДЕНТ на публичной странице. В карточке сделки менеджер
    // читал её как сообщение себе и справедливо не понимал, кто с ним говорит.
    const body = comment({ P1: 9, P2: 8, T1: null, T2: null })

    expect(body).not.toContain('Мы на вершине!')
  })

  it('пишет балл русской записью, через запятую', () => {
    // Первая версия проверяла `toContain('7')` — верно для любого форматирования числа 7,
    // то есть не проверяла ничего. Нужен дробный балл и прямое утверждение.
    const body = comment({ P1: 9, P2: 8, T1: null, T2: null })

    expect(body).toContain('8,6')
    expect(body).not.toContain('8.6')
  })

  it('называет неполноту словами', () => {
    // Балл по одному вопросу из двух выглядит так же убедительно, как по двум.
    const body = comment({ P1: 9, P2: null, T1: null, T2: null })

    expect(body).toContain('по 1 из 2')
  })

  it('не перечисляет незаполненные текстовые вопросы', () => {
    // Строка «— не ответил» на каждый пропуск превращает комментарий в перечень пустоты.
    const body = comment({ P1: 9, P2: 8, T1: 'Всё отлично', T2: null })

    expect(body).toContain('Что понравилось')
    expect(body).not.toContain('Что улучшить')
  })

  it('обезвреживает разметку, пришедшую из ответа клиента', () => {
    // Гвард под находку панели ревью PR #22. Первая версия проверяла только то, что МЫ
    // не строим разметку, и фиксировала как правильное то, что скобки респондента доезжают
    // живыми. А ссылка на анкету открыта постороннему человеку, и его текст едет в карточку
    // сделки, которую сотрудники клиента читают с доверием к источнику: `[URL=…]Счёт
    // на оплату[/URL]` выглядел бы там ссылкой, поставленной коллегой.
    const body = comment({ P1: 9, P2: 8, T1: '[URL=http://чужой]Счёт на оплату[/URL]', T2: null })

    expect(body).not.toContain('[URL=')
    expect(body).not.toContain('[/URL]')
    // Текст при этом ЦЕЛ: обезвредили начертание скобок, а не выбросили слова.
    expect(body).toContain('Счёт на оплату')
    expect(body).toContain('http://чужой')
  })

  it('НАША разметка остаётся, разметка респондента — нет (issue #26)', () => {
    // ⚠ Вся защита держится на этой асимметрии, и проверять её надо одним утверждением,
    // а не двумя разными тестами: лента разбирает описание дела как BB-код — замерено глазами
    // 25.09, причём НЕЗАВИСИМО от объявленного `DESCRIPTION_TYPE` (дела с типами `1` и `2`
    // и одинаковым текстом нарисованы одинаково). Значит `[B]` в наших заголовках — рабочая
    // разметка, и ровно поэтому такие же скобки из ответа постороннего человека обязаны
    // приезжать обезвреженными. Понизить тип и снять обезвреживание нельзя: тип разбором
    // не управляет.
    //
    // Сломайся любая половина — и результат выглядит правдоподобно: либо запись теряет блоки
    // и становится простынёй, либо respondent получает управление вёрсткой чужой CRM.
    const body = comment({ P1: 9, P2: 8, T1: '[B]как будто заголовок[/B]', T2: null })

    expect(body).toContain('[B]')
    expect(body).toContain('как будто заголовок')
    expect(body).not.toContain('[B]как будто заголовок[/B]')
  })

  it('не обезвреживает формулировку вопроса — её писал сотрудник портала', () => {
    // Уровень доверия к тексту из шаблона тот же, что к самой CRM. Обезвреживать его значит
    // молча портить то, что сотрудник набрал осознанно.
    const withBrackets: SurveyTemplate = {
      ...TEMPLATE,
      sections: [
        TEMPLATE.sections[0]!,
        {
          ...TEMPLATE.sections[1]!,
          questions: [{ ...TEMPLATE.sections[1]!.questions[0]!, title: 'Что понравилось [важно]' }],
        },
      ],
    }
    const answers = { P1: 9, P2: 8, T1: 'Всё' }

    expect(buildAnswerComment(withBrackets, answers, scoreSurvey(withBrackets, answers)))
      .toContain('Что понравилось [важно]')
  })

  it('не показывает итоговый балл, когда его нет', () => {
    // Мутация «показывать всегда, подставляя ноль» пережила первую версию тестов: её ловил
    // только посторонний тест про пустую строку. Здесь в комментарии ЕСТЬ содержимое —
    // текстовый ответ, — и именно поэтому отсутствие балла видно отдельно.
    // «Итоговый балл: 0» на анкете, где клиент ничего не оценивал, — это худшая оценка,
    // выставленная приложением за клиента. Нашла панель ревью PR #22.
    const body = comment({ P1: null, P2: null, T1: 'Пара слов', T2: null })

    expect(body).toContain('Пара слов')
    expect(body).not.toContain('Итоговый балл')
  })

  it('не приписывает «по N из M», когда ответили на всё', () => {
    // Мутация «показывать пометку всегда» пережила первую версию: тест на полностью
    // отвеченную секцию проверял только наличие балла. Нашла панель ревью PR #22.
    const body = comment({ P1: 9, P2: 8, T1: null, T2: null })

    expect(body).toContain('Продукт: 8,6')
    expect(body).not.toContain('из 2')
  })

  it('пропускает текстовый ответ из одних пробелов', () => {
    // Мутация «убрать проверку на пробельную строку» пережила первую версию: единственный
    // тест на пропуск передавал `null`, и ветка с пустой строкой не задействовалась ни разу.
    // Респондент, стёрший текст перед отправкой, — обычное дело, и пустой блок
    // «Что улучшить:» в карточке выглядит поломкой. Нашла панель ревью PR #22.
    const body = comment({ P1: 9, P2: 8, T1: 'Всё отлично', T2: '   ' })

    expect(body).toContain('Что понравилось')
    expect(body).not.toContain('Что улучшить')
  })

  it('говорит, когда в оцениваемой секции не ответили вовсе', () => {
    // Молчание по целой секции — это сигнал, а не пустое место: менеджер должен
    // увидеть, что его не оценили, а не решить, что опрос сломался.
    const body = comment({ P1: null, P2: null, T1: 'Пара слов', T2: null })

    expect(body).toContain('без оценки')
  })

  it('пишет комментарий и на пустую анкету: молчание тоже сигнал', () => {
    // Человек открыл анкету и отправил её, не ответив ни на что. Промолчать об этом
    // в сделке хуже, чем сказать: менеджер увидел бы опрос в статусе «пройден» и ни следа
    // в истории, и решил бы, что приложение потеряло ответ.
    const body = comment({ P1: null, P2: null, T1: null, T2: null })

    expect(body).toContain('Опрос пройден')
    expect(body).toContain('без оценки')
  })

  it('отдаёт пустую строку, когда сказать нечего вовсе', () => {
    // Портал отвергает пустой комментарий (`INVALID_ARG_VALUE`). Проверяем сами,
    // а не отправляем вслепую и ловим отказ. Случай вырожденный — анкета из одних
    // незаполненных открытых вопросов, — но именно он и даёт пустой текст.
    const openOnly: SurveyTemplate = { ...TEMPLATE, sections: [TEMPLATE.sections[1]!] }

    expect(buildAnswerComment(openOnly, { T1: null, T2: null }, scoreSurvey(openOnly, {}))).toBe('')
  })

  it('выносит итоговый балл отдельной строкой', () => {
    const body = comment({ P1: 9, P2: 8, T1: null, T2: null })

    expect(body).toContain('Итоговый балл: 8,6')
  })
})
