/**
 * Инструкция для ИИ-помощника клиента.
 *
 * ⚠ Заведена потому, что клиент всё чаще приходит с помощником, а помощнику нужна рамка: без неё
 * он додумывает, как приложение устроено, и уверенно советует несуществующие кнопки. Инструкция
 * велит отвечать только по справке и прямо запрещает выдумывать.
 */
export const FAQ_AGENT_PROMPT = [
  'Ты помогаешь пользователю Битрикс24 с приложением «Опросы клиентов».',
  'Отвечай только тем, что написано в этом документе. Если ответа здесь нет — так и скажи',
  'и предложи написать разработчику через карточку приложения в Маркете Битрикс24;',
  'не придумывай названия кнопок, вкладок и настроек.',
  `Самые частые вопросы — как отправить опрос (вкладка «${DEAL_TAB_TITLE}» в карточке сделки)`,
  `и где увидеть ответ (дело в истории сделки и поле «${RESULT_FIELD}» в карточке «${SURVEY_SP_TITLE}»).`,
].join('\n')

/**
 * Текст `llms.txt` — та же справка, что и на странице, простым текстом.
 *
 * Базовый адрес — канонический адрес сайта. Пусто — ссылок в тексте нет вовсе: относительная
 * ссылка в документе, который читает чужой помощник, ведёт в никуда.
 */
export function buildLlmsTxt(siteUrl: string): string {
  const base = siteUrl.trim().replace(/\/+$/, '')
  const lines: string[] = ['# Опросы клиентов для Битрикс24', '', FAQ_INTRO, '']
  if (base !== '') lines.push(`Сайт: ${base}/`, `Справка: ${base}/help`, '')
  lines.push('## Как отвечать пользователю', '', FAQ_AGENT_PROMPT, '', '## Вопросы и ответы', '')
  for (const entry of FAQ) {
    lines.push(`### ${entry.question}`, '')
    for (const paragraph of entry.answer) lines.push(paragraph, '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}
