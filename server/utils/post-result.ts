// Результат опроса возвращается в таймлайн сделки (#18) — Nitro-слой: ядро про REST не знает.
//
// Зачем. Симметрия к приглашению: ссылка уходит ИЗ сделки на переходе стадии, результат должен
// ВЕРНУТЬСЯ в неё, когда клиент ответил. До сих пор заполненная анкета оседала только в нашей базе:
// менеджер, ведущий сделку, не видел ни оценки, ни комментария — а ровно за этим сервис и ставят.
// Дело в таймлайне закрывает это без единого нового экрана: сводка «вопрос → значение» лежит там же,
// где и призыв отправить приглашение, под правами портала и его сроками хранения.
//
// ⚠️ Зависимости внедряются (`postResult(info, deps)`), а не резолвятся внутри — тем же приёмом и по
// той же причине, что `invite-issue.ts`/`close-invite.ts`: внутри три ранних выхода, и каждый
// полностью выключает фичу. Сборка боевых зависимостей — в `portal-deps.ts`, ОБЩАЯ для обоих
// побочных действий: клиент портала у них один, и второй раз строить его на тот же ответ незачем.
import { activityConfigurableAdd, buildSurveyResultActivity, ensureActivityMarker } from '~core/bitrix24/activity'
import { resultMarker } from '~core/bitrix24/invite-delivery'
import type { AnsweredInfo } from '~core/api/handlers'
import { errInfo } from '~core/obs/logger'
import { withDeadline } from './deadline'
import type { PortalActionDeps } from './portal-deps'

/**
 * Дедлайн на работу с порталом, мс — ТОТ ЖЕ, что у закрытия дела, и по той же причине: хук ждут ДО
 * отдачи 200, а человек, уже заполнивший анкету, всё это время висит на «Отправить».
 *
 * ⚠️ Оба действия запускаются ПАРАЛЛЕЛЬНО (`server/utils/api.ts`), поэтому respondent ждёт не сумму,
 * а максимум. Последовательный запуск дал бы 6 секунд ожидания на самом видимом клиенту экране.
 */
export const RESULT_DEADLINE_MS = 3000

/**
 * Что нужно записи результата, кроме самого ответа. Тип общий с закрытием дела (`portal-deps.ts`):
 * оба действия идут в один портал на один ответ, и клиент у них тоже один.
 */
export type PostResultDeps = PortalActionDeps

/**
 * Положить результат опроса в таймлайн сделки.
 *
 * ⚠️ Best-effort по построению: **ответ клиента дороже записи в CRM**. Всё, чего может не быть
 * (портала нет, сделки нет в снимке), — штатный выход без шума; отказ портала логируется, но наружу
 * не идёт. Заставить человека заполнять анкету заново из-за недоступности CRM — худшее, что тут
 * можно сделать.
 *
 * ⚠️ Ответ БЕЗ приглашения (публичная ссылка) сделки в снимке не несёт — записывать некуда, и это
 * норма, а не отказ: такой ответ живёт в аналитике, а не в карточке.
 */
export async function postResult(info: AnsweredInfo, deps: PostResultDeps): Promise<void> {
  const dealId = info.context.dealId
  // ⚠️ Проверяем ФОРМУ, а не только наличие — как в закрытии дела: `crmContextSchema.dealId` это
  // просто `z.number().optional()`, а значение уходит в `ownerId` создаваемого дела. Ноль или дробь
  // молча создали бы запись не там, где её ждут, и найти её было бы нечем.
  if (dealId === undefined || !Number.isInteger(dealId) || dealId <= 0) return

  // ⚠️ Гейт анонимности (#18). Дело в таймлайне показывает менеджеру, что ответил ИМЕННО ЭТОТ клиент
  // по ИМЕННО ЭТОЙ сделке — качественно другое раскрытие, чем агрегаты дашборда с подавлением малых
  // выборок. Опрос, обещавший на интро «Анонимно», ставит `resultToTimeline: false`, и запись сюда
  // не доходит. Отказ ВИДЕН в логе: молчаливый пропуск неотличим от «фича сломалась».
  if (!info.resultToTimeline) {
    // ⚠️ `dealId` в эту строку НЕ кладём. Гейт стоит ровно затем, чтобы не связывать ответ с
    // конкретной сделкой, — а связка «эта сделка ↔ этот опрос ↔ момент ответа» в операторском логе
    // это то же раскрытие, только в другом хранилище и с другим сроком хранения. Факт «фича не
    // сломалась, а осознанно промолчала» доказывается и без номера сделки.
    deps.log.info('b24_result_skipped', {
      surveyKey: info.surveyKey, reason: 'опрос не отдаёт индивидуальный результат в карточку'
    })
    return
  }

  const work = (async (): Promise<void> => {
    const client = await deps.portalClient()
    if (!client) return // приложение не установлено / режим памяти — сервис работает сам по себе

    // ⚠️ Маркер пишется ЗАРАНЕЕ, и сегодня его никто не читает — это не идемпотентность, а якорь:
    // по нему дело можно будет найти (страница результата, поиск виджета по нашим делам) и по нему же
    // будущая ПОВТОРНАЯ запись узнает свою. Дубля сегодня нет по другой причине: хук зовётся ровно раз
    // на записанный ответ (`stored:false` отвечает 409 РАНЬШЕ хука), а `responseId` рождается свежим.
    // ⚠️ Появится ретрай хука (очередь, outbox) — тогда сюда обязан прийти поиск по маркеру ПЕРЕД
    // созданием, как у выписки приглашения (`deliverInvite`). Без него ретрай положит второе дело:
    // Bitrix24 уникальность `ORIGIN_ID` не форсит, проверено вживую.
    const marker = resultMarker(info.responseId)
    const activityId = await activityConfigurableAdd(client, buildSurveyResultActivity({
      dealId,
      surveyTitle: info.surveyTitle,
      lines: [...info.lines],
      marker,
      // Идентификатор записи — в кнопку «Открыть результат» (#18). Тот же, из которого построен
      // маркер, но передаётся отдельно: форма маркера это деталь дедупа, и разбирать её ради кнопки
      // значило бы связать их молча.
      responseId: info.responseId,
      ...(info.context.responsibleId != null ? { responsibleId: info.context.responsibleId } : {})
    }))

    // ⚠️ ПЕРЕЧИТЫВАЕМ маркер, а не верим вызову — ровно как выписка приглашения. Принимает ли
    // `crm.activity.configurable.add` поля `originatorId`/`originId` в своём `fields`, вживую не
    // сверено; без сверки лог рапортовал бы об успехе там, где дело создано БЕЗ маркера — то есть
    // найти его потом (и не создать второе) было бы нечем.
    const fix = await ensureActivityMarker(client, activityId, marker)
    deps.log[fix === 'failed' ? 'warn' : 'info']('b24_result_posted', {
      surveyKey: info.surveyKey,
      dealId,
      responseId: info.responseId,
      activityId,
      lines: info.lines.length,
      // `already` — маркер приняла сама `configurable.add`; `repaired` — дописали; `failed` — дела с
      // маркером нет, и найти его потом будет нечем.
      // ⚠️ Первый живой прогон отвечает на вопрос раз и навсегда: `already` значит, что перечитывание
      // (`crm.activity.get` на каждый ответ) можно снимать.
      markerFix: fix
    })
  })().catch((e: unknown) => {
    deps.onFailure?.()
    // Результата в таймлайне не будет — менеджер увидит ответ только в дашборде. Неприятно, но
    // ответ записан, а это главное.
    // ⚠️ Ловим ЗДЕСЬ, а не снаружи `withDeadline`: после истечения дедлайна работа доигрывает уже без
    // ожидающего, и её отказ иначе всплыл бы unhandled rejection после завершения запроса.
    // ⚠️ `errInfo`, а не `.message`: `scrubSecrets` живёт именно в нём, а строку тут инициирует
    // НЕАВТОРИЗОВАННЫЙ запрос.
    deps.log.warn('b24_result_post_fail', { surveyKey: info.surveyKey, dealId, err: errInfo(e) })
  })

  await withDeadline(work, deps.deadlineMs ?? RESULT_DEADLINE_MS, () => {
    deps.log.warn('b24_result_post_timeout', {
      surveyKey: info.surveyKey, dealId, afterMs: deps.deadlineMs ?? RESULT_DEADLINE_MS
    })
  })
}
