import { SlidingWindowLimiter } from '~core/api/ratelimit'

/**
 * Лимит запросов дашборда (#49): потолок **на портал** плюс явный глобальный.
 *
 * ⚠️ Повод не «оптимизация». `/api/dashboard/:key` читает в память ВСЕ ответы опроса и считает по
 * ним восемь агрегатов синхронно. С мультитенантом один сотрудник одного портала, зажавший F5 на
 * большом опросе, выедает пул соединений и event loop **всем арендаторам** сразу — то есть чужие
 * порталы получают отказ из-за чужой активности. До SQL-агрегации (тот же #49) потолок это
 * ограничитель, а не решение: он режет частоту, но один запрос по-прежнему поднимает всё в память.
 *
 * **Ключ — числовой `portal.id` из подписанной сессии**, поэтому потолок ставится ПОСЛЕ
 * подтверждения тенанта: подделать такой ключ нельзя. Он же единственно верный на этом роуте, потому
 * что за корпоративным прокси все сотрудники приходят одним адресом (урок пер-IP потолка handshake:
 * низкий порог на общий адрес давал 429 одиннадцатому открытию виджета за минуту).
 *
 * ⚠️ **Пер-IP потолка здесь НЕТ, и это решение, а не пропуск.** Страница `/d/:key` рендерится на
 * сервере и зовёт этот роут внутренним вызовом (`useRequestFetch`); у внутреннего вызова сокета нет,
 * и `clientIp` честно отдаёт `unknown` (`src/api/client-ip.ts`, ветка `socket === null` — до чтения
 * `X-Forwarded-For`, так что `TRUSTED_PROXIES` не помогает). Значит пер-IP потолок на главном пути
 * вырождается в ОДИН счётчик на все порталы — и, стоя до гейта сессии, превращается в дешёвый
 * неавторизованный отказ дашборда всему сервису: `GET /d/что-угодно` раз в секунду выжигает общий
 * бакет. Это ровно тот кросс-тенантный отказ, ради устранения которого потолок и заводился. Урок в
 * проекте уже измерен и записан (`src/api/handlers.ts`, `invitationCheck`) — здесь он повторён бы
 * заново. Пер-респондентная гранулярность на SSR-пути упирается в доверенный прокси и делается там
 * ([#148](https://github.com/bx-shef/polls/issues/148)), а не тут.
 *
 * ⚠️ Запрос БЕЗ cookie сессии до этого потолка не доходит вовсе: он отсекается проверкой HMAC, без
 * обращения к базе. Флуд без сессии стоит нам одной проверки подписи.
 *
 * ⚠️ Глобальный потолок ставится ЯВНО: сумма пер-портальных потолков растёт с числом установленных
 * порталов, а пул соединений — нет. Это же и закрывает обход «чередованием порталов», из-за которого
 * раздельные счётчики в проекте по умолчанию не заводят (карта, §Мультитенант).
 *
 * In-memory, на инстанс (общий стор — #4): рестарт сбрасывает окно ≤60 секунд, это fail-open на одно
 * окно, и цена его здесь ниже, чем round-trip в ту самую базу, которую потолок защищает.
 */
export interface DashboardLimiterOptions {
  /** Потолок на портал за окно. */
  portalLimit?: number
  /** Суммарный потолок инстанса за окно. */
  globalLimit?: number
  /** Длина окна, мс. Одна на оба потолка — разные окна дали бы неочевидную границу. */
  windowMs?: number
}

export interface DashboardLimiter {
  /** true — запрос допущен (и учтён) потолками портала и инстанса. Зовётся ПОСЛЕ резолва тенанта. */
  allowPortal(portalId: number | undefined, now?: Date): boolean
}

/**
 * Ключ портала в режиме памяти/dev: `portalId` там `undefined`, но потолок нужен и в нём.
 * ⚠️ Это тот же класс «общего ключа», что и `unknown` выше, — и он допустим ровно потому, что
 * порталов в этом режиме нет вовсе: общий ключ там никого не задевает.
 */
const MEMORY_PORTAL_KEY = 'memory'
const GLOBAL_KEY = 'all'

/**
 * Фабрика — чтобы тест мог собрать свой экземпляр с крошечными потолками и своими часами. Боевой
 * экземпляр ниже; модульное состояние на процесс, как у остальных лимитеров.
 */
export function createDashboardLimiter(opts: DashboardLimiterOptions = {}): DashboardLimiter {
  const windowMs = opts.windowMs ?? 60_000
  const portal = new SlidingWindowLimiter({ limit: opts.portalLimit ?? 60, windowMs })
  const global = new SlidingWindowLimiter({ limit: opts.globalLimit ?? 600, windowMs })
  return {
    // ⚠️ Порядок операндов НЕ косметика: `&&` замыкается, и второй потолок при отказе первого не
    // тратится. Пер-портальный стоит первым намеренно — шумный арендатор жжёт СВОЙ счётчик прежде
    // общего. ⚠️ Честная граница: при исчерпанном ГЛОБАЛЬНОМ потолке пер-портальный уже списан, то
    // есть «отказ соседа не тратит мой бюджет» верно только в одну сторону. Перестановка меняет это
    // свойство, а не порядок слагаемых.
    allowPortal: (portalId, now = new Date()) =>
      portal.allow(portalId === undefined ? MEMORY_PORTAL_KEY : String(portalId), now) &&
      global.allow(GLOBAL_KEY, now)
  }
}

/** Боевой экземпляр роута дашборда. */
export const dashboardLimiter = createDashboardLimiter()

