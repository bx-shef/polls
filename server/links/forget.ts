import { and, eq, inArray, isNotNull, lt, notInArray } from 'drizzle-orm'
import { getDb, schema } from '../db/client'

/**
 * Forgetting what an expired invitation knew about people.
 *
 * ⚠ ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Соседи по каталогу — про выпуск (`issue.ts`) и про показ
 * страницы (`store.ts`). Этот путь не вызывается ни оттуда, ни оттуда: его зовёт фоновый
 * тик, у него свой предохранитель и своя цена ошибки. Уборщик, спрятанный внутри модуля
 * выпуска, находится только грепом.
 */

/**
 * Стереть шапки истёкших приглашений.
 *
 * ⚠ НАЙДЕНО ИНВЕНТАРИЗАЦИЕЙ БАЗЫ 25.09, и это был не пробел, а НЕПРАВДА В КОММЕНТАРИИ.
 * `link_index.header` — единственное место в схеме, где лежат имена людей: компания, проект,
 * кого спрашиваем, кто спрашивает. И `schema.ts`, и `revokeLink` утверждали, что снимок
 * стирается, «когда ссылка приходит в конечное состояние», и прямо называли истёкшие в том же
 * ряду, что пройденные и отозванные. На деле `header: null` стоял ровно в двух местах —
 * `markCompleted` и `revokeLink`, — а статус `expired` не выставлялся НИКОГДА: истечение
 * считается на чтении, сравнением `expires_at` с часами.
 *
 * Отсюда цена: приглашение, которое выпустили и по которому никто не прошёл, держало имена
 * клиента у нас ВЕЧНО — и переживало собственный срок жизни, и уход клиента с приложения
 * (уборщик мёртвых грантов обнуляет токены, но строку портала оставляет, поэтому каскад
 * не срабатывает). Это самый обычный исход опроса: человек не ответил.
 *
 * ⚠ Сама строка остаётся, и это осознанно. Без неё посторонний, открывший старую ссылку,
 * получил бы «ссылки не существует» вместо «срок действия истёк» — а объяснить человеку,
 * что произошло, и есть работа этой страницы. После стирания шапки в строке не остаётся
 * ничего о людях: хеш токена, идентификатор элемента портала, код и версия анкеты, даты.
 *
 * ⚠ ПРОЙДЕННУЮ И ОТОЗВАННУЮ НЕ ТРОГАЕМ ВОВСЕ, и это не перестраховка. Переписать
 * `completed` на `expired` значит стереть след того, что человек ответил, — ровно то, что
 * `revokeLink` отказывается делать по той же причине. Сегодня такая строка невозможна
 * (оба перехода обнуляют шапку тем же `UPDATE`, которым меняют статус, то есть под выборку
 * не попадают), но цена ошибок здесь несимметрична: лишнее условие стоит ноль, а потерянный
 * признак «ответ получен» не восстановить.
 *
 * ⚠ Условие по шапке ПОВТОРЕНО в самом `UPDATE`, а не оставлено в подзапросе: между выборкой
 * и записью ссылку могли пройти. Приём тот же, что у `purgeExpiredAnswers`.
 *
 * ⚠ Потолок за заход и `portalId` — по тем же причинам, что у соседних уборщиков: у `update`
 * с подзапросом нет `limit`, а тест обязан уметь ограничиться своим порталом, иначе прогон
 * `pnpm check` с боевым `DATABASE_URL` стёр бы шапки чужих клиентов. Приложение зовёт без
 * портала и убирает всё.
 *
 * Возвращает, сколько шапок стёрто.
 */
export async function forgetExpiredLinkHeaders(
  now: Date,
  options: { limit?: number, portalId?: string } = {},
): Promise<number> {
  const db = getDb()
  const limit = options.limit ?? 200

  const scope = and(
    // Строгое «раньше»: ссылка, истекающая ровно сейчас, ещё может открыться на этой же
    // миллисекунде — правильная сторона ошибки та, где человек видит анкету.
    lt(schema.linkIndex.expiresAt, now),
    isNotNull(schema.linkIndex.header),
    notInArray(schema.linkIndex.status, ['completed', 'revoked']),
    ...(options.portalId === undefined ? [] : [eq(schema.linkIndex.portalId, options.portalId)]),
  )

  // Порядок по сроку: упёршись в потолок, забываем самые давние, а не случайные.
  const due = db.select({ id: schema.linkIndex.id }).from(schema.linkIndex).where(scope)
    .orderBy(schema.linkIndex.expiresAt)
    .limit(limit)

  const rows = await db
    .update(schema.linkIndex)
    .set({ header: null, status: 'expired' })
    .where(and(inArray(schema.linkIndex.id, due), isNotNull(schema.linkIndex.header)))
    .returning({ id: schema.linkIndex.id })

  return rows.length
}
