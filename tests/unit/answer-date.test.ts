import { describe, expect, it } from 'vitest'
import { formatAnswerDate, isCalendarDate, isoDay } from '../../shared/answer-date'

/**
 * Дата ответа: что считается датой и как она читается по-русски.
 *
 * Одно определение на виджет публичной страницы, проверку присланного, виджет в карточке
 * «Результата опросов» и дело в ленте сделки.
 * До issue #84 (п. 13) вопрос «Дата» принимал любой текст, виджет переводил в русскую запись
 * только ISO, а лента печатала всё как есть — одно прохождение выглядело в двух местах
 * двумя разными датами.
 */

describe('что считается датой', () => {
  it.each(['2026-09-28', '2026-01-01', '2026-12-31', '2028-02-29', '2000-02-29', '1900-01-01', '2100-12-31'])(
    'настоящая дата в записи ГГГГ-ММ-ДД — дата (%s)',
    (text) => {
      expect(isCalendarDate(text)).toBe(true)
    },
  )

  it.each<[string, string]>([
    ['2026-02-30', 'тридцатого февраля не бывает'],
    ['2026-02-29', '2026 не високосный'],
    ['1900-02-29', '1900 делится на 100 и не делится на 400 — не високосный'],
    ['2026-04-31', 'в апреле тридцать дней'],
    ['2026-13-01', 'тринадцатого месяца нет'],
    ['2026-00-10', 'нулевого месяца нет'],
    ['2026-09-00', 'нулевого дня нет'],
    ['0000-01-01', 'нулевого года нет'],
  ])('дата, которой нет в календаре, — не дата (%s: %s)', (text) => {
    // ⚠ Проверка без `Date`, и эти случаи — ровно то, где `Date` соврал бы: в Node
    // `new Date('2026-02-30')` — это 2 марта, без всякой ошибки.
    expect(isCalendarDate(text)).toBe(false)
  })

  it.each<[string, string]>([
    ['28.09.2026', 'русская запись — это показ, а не провод'],
    ['09/28/2026', 'американская запись, которую охотно понимает `Date.parse`'],
    ['2026-9-28', 'без ведущих нулей'],
    ['2026-09-28T00:00:00', 'дата со временем'],
    ['в пятницу', 'свободный текст'],
    ['', 'пусто'],
  ])('не запись ГГГГ-ММ-ДД — не дата (%s: %s)', (text) => {
    expect(isCalendarDate(text)).toBe(false)
  })

  it.each<[string, string]>([
    ['0026-09-28', '«28.09.26», набранное по привычке: поле набора не дописывает век'],
    ['0202-09-28', 'год «2026», набранный наполовину: поле отдаёт дату после каждой цифры'],
    ['1899-12-31', 'на день раньше окна'],
    ['2101-01-01', 'на день позже окна'],
    ['9999-12-31', 'верх записи из четырёх цифр'],
  ])('год вне окна 1900–2100 — не дата (%s: %s)', (text) => {
    // ⚠ Гвард под находку `/review` и `/code-review` в PR #91: такие дни есть в календаре,
    // и проверка их принимала, а одноразовая ссылка закрывалась — в карточке навсегда
    // оставалось «28.09.0026».
    expect(isCalendarDate(text)).toBe(false)
  })
})

describe('запись провода', () => {
  it('собирается из полей даты с ведущими нулями', () => {
    expect(isoDay({ year: 2026, month: 9, day: 5 })).toBe('2026-09-05')
  })

  it('недонабранный год остаётся недонабранным — и проверку не проходит', () => {
    // Запись честно повторяет то, что отдало поле, а решает проверка: виджет и сервер
    // зовут одну и ту же `isCalendarDate`, и расходиться им негде.
    expect(isoDay({ year: 26, month: 9, day: 28 })).toBe('0026-09-28')
    expect(isCalendarDate(isoDay({ year: 26, month: 9, day: 28 }))).toBe(false)
  })
})

describe('дата по-русски', () => {
  it('переводит ISO в запись ДД.ММ.ГГГГ', () => {
    expect(formatAnswerDate('2026-09-28')).toBe('28.09.2026')
    expect(formatAnswerDate('2026-01-05')).toBe('05.01.2026')
  })

  it('не смущается пробелами вокруг даты', () => {
    expect(formatAnswerDate(' 2026-09-28\n')).toBe('28.09.2026')
  })

  it.each<[string, string]>([
    ['в пятницу', 'свободный текст из времён, когда дата была текстовым полем'],
    ['28.09', 'неполная дата'],
    ['2026-02-30', 'похоже на дату, но её нет в календаре'],
  ])('не дату возвращает КАК ПРИШЛА (%s: %s)', (text) => {
    // ⚠ Это ответ клиента: выбросить его нельзя, а выдать за дату — тем более.
    // `2026-02-30`, переставленное в `30.02.2026`, выглядело бы проверенной датой.
    expect(formatAnswerDate(text)).toBe(text)
  })
})
