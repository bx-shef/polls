/**
 * The owner's mark on everything the app creates in a client portal.
 *
 * ⚠ Решение владельца 28.09 (issue #84, пункт 22): смарт-процессы, подписи наших полей
 * и вкладки носят префикс `[sh]`. Зачем, по пунктам:
 * - в списках смарт-процессов, полей и вкладок клиента наше отличается от его собственного
 *   с первого взгляда — полей в карточке сделки у клиента десятки;
 * - «Опрос» и «Шаблон опроса» — обычные слова, и по названию мы находим смарт-процесс,
 *   если потеряли его идентификатор (`findTypeByTitle`). С префиксом шанс «усыновить»
 *   чужой одноимённый смарт-процесс клиента падает почти до нуля;
 * - это метка владельца, а не бренд приложения: её видит администратор портала, а клиент
 *   на публичной странице анкеты её не видит нигде.
 *
 * Коды полей (`UF_CRM_…`) префикса не получают: портал их не переименовывает, а новые
 * поля со старыми данными не связаны.
 */
export const OWNER_PREFIX = '[sh]'

/** Подпись с меткой владельца: `[sh] Код шаблона`. */
export function ownerLabel(text: string): string {
  return `${OWNER_PREFIX} ${text}`
}
