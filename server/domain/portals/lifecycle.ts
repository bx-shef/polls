/**
 * When a portal stops being ours, and when we may erase it.
 *
 * ⚠ Существует потому, что штатного способа узнать об удалении приложения у нас НЕТ,
 * и это не упущение, а свойство тиражного приложения с пунктом в левом меню. Проверено
 * на живом портале 18.09.2026: после `installFinish()` событие `ONAPPINSTALL` не приходит,
 * а `application_token` приходит ТОЛЬКО в событиях. Для `ONAPPUNINSTALL` сравнение этого
 * токена — единственный способ проверки в принципе: данных авторизации в событие удаления
 * не передают, приложение уже удалено. Без токена обработчик принимал бы «сотрите портал X»
 * от кого угодно из интернета, то есть был бы кнопкой отключения чужого клиента.
 *
 * Значит об уходе клиента мы узнаём не из события, а из ВЫВОДА: портал перестал принимать
 * наш грант. Это надёжнее события — его не подделать снаружи, потому что это наш собственный
 * исходящий вызов, — но медленнее, и потому здесь есть отсрочка.
 *
 * Приём и его обоснование взяты у `client-bank-alfa-by` (`grant_revoked_at`, уборщик #574),
 * где это оплачено живыми клиентами. Там же формулировка главной ловушки: отметку нельзя
 * переписывать на каждом отказе, иначе срок отодвигается вечно и уборщик не срабатывает
 * никогда, продолжая выглядеть рабочим.
 */

/**
 * Отказы, после которых грант считается мёртвым.
 *
 * ⚠ Функция принимает результат `safeRefusal`, а НЕ текст ошибки портала. Это несущее
 * различие: в тексте портала может ехать процитированный ответ клиента (Битрикс24 любит
 * цитировать присланное значение в ошибке валидации), и респондент, набравший в анкете
 * `expired_token`, объявлял бы грант своего же портала мёртвым. `safeRefusal` выбирает
 * из закрытого списка наших констант, поэтому чужой текст сюда не попадает по построению.
 *
 * ⚠ `INVALID_CREDENTIALS` в списке НЕТ намеренно. Он означает «неверные данные запроса»,
 * то есть может указывать на нашу пару `client_id`/`client_secret`, а не на портал. Ошибка
 * в ней пометила бы мёртвыми ВСЕ порталы разом — цена несопоставима с пользой.
 */
const DEAD_GRANT_REFUSALS: readonly string[] = [
  // Портал удалён целиком. Однозначен.
  'PORTAL_DELETED',
  // Дошло до нас — значит реактивное продление SDK уже не сработало: обменивать нечего.
  'expired_token',
  // «Wrong authorization data»: токен не принят и обновить его не вышло.
  'NO_AUTH_FOUND',
]

export function isDeadGrant(refusal: string): boolean {
  return DEAD_GRANT_REFUSALS.includes(refusal)
}

/**
 * Сколько ждём, прежде чем стереть.
 *
 * ⚠ Отсрочка обязательна, и она не про осторожность, а про обратимость. Отказ может быть
 * и не про уход клиента: портал переносили, тариф не продлили на выходные, у нас разъехался
 * ключ шифрования. Стерев токены сразу, мы заставили бы клиента переустанавливать приложение
 * из-за суточного перерыва — а стереть можно только один раз.
 *
 * Четырнадцать суток: заведомо больше выходных и новогодних каникул, заведомо меньше срока,
 * за который хранение чужих токенов становится вопросом. Ровно на эти же грабли отсрочка
 * и рассчитана — первый успешный вызов снимает отметку, и отсчёт начинается заново.
 */
export const PURGE_GRACE_DAYS = 14

const DAY_MS = 24 * 60 * 60 * 1000

/**
 * Граница: всё, что помечено РАНЬШЕ неё, пора стирать.
 *
 * Считает вызывающий и передаёт в запрос готовым значением — SQL не должен знать про политику,
 * а тест не должен подсовывать часы в базу.
 */
export function purgeBoundary(now: Date, graceDays: number = PURGE_GRACE_DAYS): Date {
  return new Date(now.getTime() - graceDays * DAY_MS)
}

/**
 * Пора ли стирать конкретный портал.
 *
 * `null` — портал не помечен, значит жив. Отметка ровно на границе не срабатывает: строгое
 * сравнение оставляет портал в живых ещё на один тик, и это правильная сторона ошибки.
 */
export function shouldPurge(revokedAt: Date | null, now: Date, graceDays: number = PURGE_GRACE_DAYS): boolean {
  if (revokedAt === null) return false
  return revokedAt.getTime() < purgeBoundary(now, graceDays).getTime()
}
