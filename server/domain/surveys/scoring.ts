import { scaleOf, type SurveyBand, type SurveyQuestion, type SurveySection, type SurveyTemplate } from './model'
import type { AnswerValue } from './answer'

/**
 * Turns answers into section scores.
 *
 * Чистая функция: шаблон и ответы на входе, баллы на выходе. Ни базы, ни портала — поэтому
 * проверяется вызовом, и проверять её надо много: это единственное место, где ответ человека
 * превращается в число, по которому потом принимают решения.
 *
 * Формула взята у источника (`legacy/LEGACY-ANALYSIS.md`, `Item::calcStructData`): по секции
 * суммируется `значение × вес / 100` по балльным вопросам, результат округляется до двух знаков.
 * Веса во всех двенадцати анкетах дают ровно 100, шкала у всех балльных вопросов 0–10 — то есть
 * балл секции это взвешенное среднее в шкале 0–10.
 *
 * ⚠ ПРОПУСК СЧИТАЕТСЯ НИЗШЕЙ ОЦЕНКОЙ ШКАЛЫ — решение владельца 28.09 (issue #84, пункт 5).
 * До него было наоборот: неотвеченный вопрос выпадал и из суммы, и из делителя, и балл считался
 * по тому, на что ответили. Владелец на живом прогоне ответил на 3 вопроса из 8 и получил итог 3,
 * будто оценил всё: молчание поднимало балл до уровня единственной поставленной оценки. Теперь
 * пропуск входит в сумму низшей оценкой, а его вес остаётся в делителе.
 *
 * ⚠ Именно НИЗШЕЙ ОЦЕНКОЙ ШКАЛЫ, а не буквальным нулём. У всех перенесённых анкет шкала 0–10,
 * и там это ровно тот ноль, о котором говорил владелец. Но конструктор разрешает шкалу 1–10
 * или 1–5, и ноль там лежит ниже шкалы: балл раздела ушёл бы туда, где нет ни одного диапазона
 * интерпретации, и клиент с пропусками не увидел бы текста вовсе — тот самый класс отказа,
 * ради которого заведён инвариант «диапазоны покрывают шкалу без дыр».
 *
 * ⚠ ХРАНЕНИЕ ЭТО НЕ МЕНЯЕТ. В ответах пропуск по-прежнему `null` — инвариант проекта: нетронутый
 * ползунок не уезжает нулём, и по сохранённым ответам всегда видно, где клиент поставил ноль сам,
 * а где промолчал. Низшей оценкой пропуск становится только здесь, в подсчёте.
 *
 * К источнику это ближе, чем было: там пропустить было нельзя, ползунок всегда имел значение,
 * и нетронутый уезжал нулём — началом шкалы 0–10. На полностью заполненной анкете с весами
 * в сумме 100 цифра та же, что у старой формулы, — сверка баллов в задаче 6 держится на этом.
 */

/** Балл одной секции и то, из чего он сложился. */
export interface SectionScore {
  key: string
  title: string
  /**
   * Балл секции в её шкале, округлённый до двух знаков.
   *
   * `null` означает «балла нет»: секция не даёт балла вовсе (секция открытых вопросов)
   * или в ней нет ни одного балльного вопроса в оценку. Секция, где не ответили ни на что,
   * балл ИМЕЕТ — низший, см. шапку файла. Ноль такой же честный балл, как десятка,
   * и путать его с отсутствием нельзя.
   */
  score: number | null
  /** На сколько балльных вопросов секции ответили. Остальные вошли в балл низшей оценкой. */
  answered: number
  /** Сколько балльных вопросов в секции идёт в оценку. */
  scored: number
  /** Диапазон интерпретации, в который попал балл: текст для респондента. */
  band: SurveyBand | null
}

export interface SurveyScore {
  sections: SectionScore[]
  /**
   * Общий балл — среднее по секциям, у которых балл есть.
   *
   * Именно среднее ПО СЕКЦИЯМ, а не взвешенное по всем вопросам сразу: секции у клиента
   * называются «Продукт», «Процессы», «Персонал» и читаются как три равноправные стороны
   * работы. Взвешивание по числу вопросов сделало бы вес стороны следствием того, сколько
   * про неё придумали спросить, — а это случайность конструктора, а не замысел.
   *
   * ⚠ Числа этого не было в старом решении: там три балла по секциям и никакого итога.
   * Заводим его ровно под две вещи, которым нужна ОДНА цифра: фильтры и роботы клиента
   * на стороне портала и порог тревоги. Главной метрикой отчёта он не выносится — это
   * инвариант проекта, и отчёт показывает доли по корзинам.
   */
  overall: number | null
}

/**
 * Посчитать баллы по всем секциям шаблона.
 *
 * Ответы приходят уже проверенными (`checkAnswers`): лишних ключей в них нет, значения
 * в шкале, пропуск выражен `null`. Здесь ещё раз это не проверяется — двойная проверка
 * расходится с оригиналом ровно тогда, когда правят одну из двух.
 */
export function scoreSurvey(template: SurveyTemplate, answers: Readonly<Record<string, AnswerValue>>): SurveyScore {
  const sections = template.sections.map(section => scoreSection(section, answers))

  const scored = sections.map(s => s.score).filter((s): s is number => s !== null)
  return {
    sections,
    overall: scored.length === 0 ? null : round2(scored.reduce((sum, s) => sum + s, 0) / scored.length),
  }
}

function scoreSection(section: SurveySection, answers: Readonly<Record<string, AnswerValue>>): SectionScore {
  // Балл дают только балльные вопросы, и только те, что помечены идущими в оценку.
  // В источнике выключение выражалось весом 0 — неотличимо от опечатки; у нас это флаг.
  const scoring = section.questions.filter(q => q.scored && q.type === 'scale')

  let weighted = 0
  let weight = 0
  let answered = 0

  for (const question of scoring) {
    const value = answers[question.key]
    // ⚠ Вес идёт в делитель ВСЕГДА, отвечен вопрос или нет: пропуск — это низшая оценка,
    // а не выпавший вопрос. Строка сюда попасть не должна, но если попадёт, это тоже пропуск.
    weight += question.weight
    if (typeof value !== 'number') {
      weighted += lowestScore(question) * question.weight
      continue
    }

    weighted += value * question.weight
    answered += 1
  }

  // ⚠ Нечисловой итог — это испорченная схема, а не оценка. Схема лежит строковым полем
  // на портале, и между ним и подсчётом стоит только проверка формы (`isTemplateShaped`),
  // а не значений: вес `1e400` даёт `Infinity`, и `NaN` уехал бы в поле «оценка клиента»
  // сделки и в заголовок дела, мимо всех проверок `=== null`. «Балла нет» здесь честнее.
  // Нашла панель ревью PR #85.
  const raw = weighted / weight
  const score = !section.scored || weight === 0 || !Number.isFinite(raw) ? null : round2(raw)

  return {
    key: section.key,
    title: section.title,
    score,
    answered,
    scored: scoring.length,
    band: score === null ? null : findBand(section.bands, score),
  }
}

/**
 * Низшая оценка вопроса — то, чем в балл входит пропуск.
 *
 * Умолчание шкалы общее с проверкой ответа (`scaleOf`): пропуск не может стать оценкой,
 * которую ответом поставить нельзя. Нечисловая граница — испорченная схема; тогда ноль,
 * а не `NaN` в балле.
 */
function lowestScore(question: SurveyQuestion): number {
  const { min } = scaleOf(question)
  return Number.isFinite(min) ? min : 0
}

/**
 * Найти диапазон интерпретации для балла.
 *
 * ⚠ Границы ВКЛЮЧИТЕЛЬНЫЕ с обеих сторон, а в источнике диапазоны смежные (…6–7.5, 7.5–8…).
 * Значит ровно на стыке подходят оба, и побеждает первый по порядку. Это выбор, а не
 * недосмотр: альтернатива — полуинтервалы, но тогда балл, равный верхней границе последнего
 * диапазона, не попадёт никуда, и клиент с оценкой 10 не увидит текста вовсе.
 *
 * `null` — балл не покрыт ни одним диапазоном. Такое бывает и это не ошибка расчёта:
 * в источнике диапазоны были заполнены у одной анкеты из двенадцати, а ниже четвёрки
 * не покрывалось ничем. Адаптер импорта на такие дыры ругается отдельно.
 */
export function findBand(bands: readonly SurveyBand[], score: number): SurveyBand | null {
  return bands.find(band => score >= band.from && score <= band.to) ?? null
}

/**
 * Округление до двух знаков — так, как его делает источник.
 *
 * ⚠ Округляем ОДИН раз, в самом конце. Округление промежуточных сумм копит ошибку, и балл
 * разошёлся бы с историческим на сотые — ровно на той величине, на которой сверка в задаче 6
 * и должна сойтись.
 *
 * ⚠ Эталон здесь — не «математически правильно», а «как считает PHP», потому что весь смысл
 * округления в том, чтобы наш балл совпал с историческим. Замерено:
 *
 * | значение | PHP `round()` | `Number(x.toFixed(2))` | `Math.round(x*100)/100` |
 * |---|---|---|---|
 * | 1.005 | **1.01** | 1 | 1 |
 * | 0.495 | **0.5** | 0.49 | 0.5 |
 * | 2.675 | **2.68** | 2.67 | 2.68 |
 *
 * Оба очевидных способа расходятся с PHP. Первая версия этой функции брала `toFixed`,
 * то есть худший из двух, и обосновывала выбор примером с `1.005`, которого не существует:
 * на нём оба дают одно и то же. Расхождение воспроизводится на настоящей секции — веса 1 и 99,
 * значения 0 и 0.5 дают 0.495. Нашла панель ревью PR #22.
 *
 * Работает разбор через экспоненциальную запись: `'0.495e2'` парсится как новый десятичный
 * литерал и даёт ровно 49.5, тогда как умножение `0.495 * 100` приносит двоичную погрешность
 * и даёт 49.49999999999999. Дальше обычное округление половины вверх.
 *
 * ⚠ PHP округляет половину ОТ НУЛЯ, а `Math.round` — вверх. На неотрицательных это одно и то же,
 * и прежняя редакция на этом и стояла. С 28.09 пропуск входит в балл низшей оценкой шкалы,
 * а конструктор отрицательную шкалу не запрещает — значит отрицательный балл достижим одним
 * пропуском, и `-2.675` дал бы `-2.67` вместо PHP-шных `-2.68`. Поэтому округляется модуль,
 * а знак ставится после. Нашли программист и безопасность в панели ревью PR #85.
 * Экспоненциальная запись на входе (`1e-7`) сломала бы склейку строк, но балл в такой форме
 * не приходит: он получается делением сумм в пределах шкалы.
 */
function round2(value: number): number {
  const rounded = Number(`${Math.round(Number(`${Math.abs(value)}e2`))}e-2`)
  return value < 0 && rounded !== 0 ? -rounded : rounded
}
