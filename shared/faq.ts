/**
 * The single source of the app's help: the `/help` page and `/llms.txt` both render it.
 *
 * ⚠ ОДИН ИСТОЧНИК НА ДВЕ ПОВЕРХНОСТИ, и это несущее решение. Справку читают двое: человек
 * (страница `/help`, в том числе в слайдере портала) и ИИ-помощник клиента (`/llms.txt`).
 * Две копии текста разошлись бы молча — и разошлась бы та, которую реже перечитывают, то есть
 * агентская: помощник уверенно отвечал бы клиенту устаревшее. Приём и его обоснование — у соседнего
 * проекта (`client-bank-alfa-by`, `app/utils/faq.ts`), где он оплачен живыми клиентами.
 *
 * ⚠ ЛЕЖИТ В `shared/`, а не в `app/utils/`, потому что читают его обе стороны: страница
 * (клиентский бандл) и сервер (`server/routes/llms.txt.get.ts`). Серверу ходить за этим в `app/`
 * незачем, а `shared/` для этого и заведён в Nuxt. Импортов из `server/` здесь быть не может —
 * это проверяет `pnpm check:layers`.
 *
 * ⚠ Код `app/` импортирует его ТОЛЬКО через `#shared/faq`. Относительный путь сборка Nuxt выносит
 * из серверного бандла страниц наружу с неверным адресом, и `pnpm build` падает — поймано сборкой.
 *
 * ⚠ ТЕКСТ ПЛОСКИЙ, без разметки. `llms.txt` — простой текст по устройству, а страница рисует
 * абзацы сама. Разметка в источнике заставила бы одну из сторон её вырезать, а вырезают такое
 * обычно регуляркой, которая однажды съест не то. Держит тест `tests/unit/faq.test.ts`.
 *
 * ⚠ ОТВЕТЫ ПРО «ЧТО ДЕЛАТЬ», а не «как устроено». Справку открывают, когда что-то не так,
 * и человеку нужно действие. И каждое утверждение здесь обязано быть правдой о коде: справка,
 * обещающая кнопку, которой нет, хуже отсутствующей. Роботов, пакетной рассылки и отчётов
 * в приложении пока нет — поэтому здесь о них ни слова.
 */

/** Раздел справки. `id` уходит в якорь страницы — по нему ведут контекстные ссылки «Что это значит?». */
export interface FaqEntry {
  /** Якорь: латиницей, короткий — он попадает в адрес. */
  id: string
  /** Вопрос так, как его задаёт человек. */
  question: string
  /** Ответ абзацами. Первый абзац — самый короткий ответ по существу. */
  answer: string[]
}

