/**
 * How often one visitor may hit the public survey page.
 *
 * Ограничение частоты — часть задачи про публичную страницу, а не «когда-нибудь потом».
 * Раньше оно жило зонами nginx и исчезло вместе с ним при переходе на общий хост: у общего
 * `nginx-proxy` свои настройки, они не наши и под наш роут не заточены. Значит считает
 * приложение.
 *
 * Считаем по ДВУМ ключам сразу, и это не перестраховка. По адресу — против перебора токенов:
 * атакующий пробует чужие ссылки с одной машины. По токену — против долбёжки в одну анкету
 * с разных адресов: токен уже известен, и защита по адресу тут не работает вовсе.
 *
 * Здесь только решение по счётчикам. Сами счётчики живут в Redis: домен не знает, где считают.
 */

/** Окно счёта. Минуты хватает: мы отсекаем перебор, а не выравниваем нагрузку. */
export const WINDOW_SECONDS = 60

/**
 * Пределы за окно.
 *
 * По адресу больше, чем по токену, намеренно: за одним адресом может сидеть целый офис
 * клиента, и несколько человек, открывших свои анкеты одновременно, — обычный день,
 * а не атака. По токену предел жёсткий: свою анкету не открывают двадцать раз в минуту.
 */
export const LIMITS = {
  perAddress: 60,
  perToken: 20,
} as const

/** Счётчики за текущее окно — сколько обращений уже было, не считая нынешнего. */
export interface RateCounters {
  perAddress: number
  perToken: number
}

export type RateDecision
  = | { allow: true }
    | { allow: false, by: 'address' | 'token', retryAfterSeconds: number }

/**
 * Пускать ли это обращение.
 *
 * ⚠ Счётчики приходят УЖЕ увеличенными на текущее обращение. Считать сначала, решать потом —
 * единственный порядок, при котором отказ тоже попадает в счёт: иначе отклонённые попытки
 * не учитываются, и перебор идёт ровно на пределе бесконечно.
 *
 * Адрес проверяется раньше токена: при переборе чужих токенов именно адрес и есть то общее,
 * что у попыток есть, и назвать в отказе стоит настоящую причину.
 */
export function decideRateLimit(
  counters: RateCounters,
  windowSeconds: number = WINDOW_SECONDS,
  limits: { perAddress: number, perToken: number } = LIMITS,
): RateDecision {
  if (counters.perAddress > limits.perAddress) {
    return { allow: false, by: 'address', retryAfterSeconds: windowSeconds }
  }
  if (counters.perToken > limits.perToken) {
    return { allow: false, by: 'token', retryAfterSeconds: windowSeconds }
  }
  return { allow: true }
}

/**
 * Ключ счётчика по адресу.
 *
 * Адрес нормализуется, потому что один и тот же клиент приходит то как `::ffff:1.2.3.4`,
 * то как `1.2.3.4`, и без этого у него оказалось бы два счёта вместо одного.
 *
 * ⚠ Адрес в ключ уходит хешем, а не как есть. IP посетителя анкеты — персональные данные
 * постороннего человека, и хранить их у себя, даже на минуту и даже в Redis, мы не обязаны:
 * для счёта достаточно различать адреса, а не знать их.
 *
 * ⚠ `scope` разделяет счёт публичной анкеты и портальных экранов. Общий ключ при РАЗНЫХ
 * пределах (60 и 120) даёт неочевидную беду: сотрудники наработали за минуту 70 обращений
 * из офиса — портальный предел не тронут, а респондент с того же адреса получает
 * «слишком много попыток» за чужую активность и не может ответить на анкету вовсе.
 * Отдельные пространства убирают этот класс целиком.
 */
export function addressKey(
  address: string,
  hash: (value: string) => string,
  scope: 'public' | 'portal' = 'public',
): string {
  const normalized = address.trim().toLowerCase().replace(/^::ffff:/, '')
  return `rate:addr:${scope === 'portal' ? 'portal:' : ''}${hash(normalized)}`
}

/** Ключ счётчика по токену. Токен и здесь не хранится — только его хеш. */
export function tokenKey(tokenHash: string): string {
  return `rate:link:${tokenHash}`
}

/**
 * Адрес обращающегося из заголовка прокси.
 *
 * ⚠ Берём ПОСЛЕДНЕЕ значение `X-Forwarded-For`, а не первое, и это не вкусовщина.
 * Стандартный `proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for` не заменяет
 * заголовок, а ДОПИСЫВАЕТ реальный адрес в конец. Значит доверенное значение — последнее,
 * а первое прислал сам обращающийся. `getRequestIP` из h3 берёт именно первое
 * (`split(',').shift()`), то есть считает по значению, которое подделывается одной строкой
 * в запросе, — и весь предел по адресу снимается. Нашла панель ревью PR #15.
 *
 * Когда прокси не дописывает, а заменяет заголовок, в списке одно значение — первое и есть
 * последнее, так что для обеих топологий верно одно правило: перед нами ровно один
 * доверенный прокси, и его слово последнее.
 *
 * Пусто — значит заголовка нет вовсе (прямое обращение в обход прокси): тогда адрес берётся
 * из сокета, и решает это вызывающий.
 */
export function trustedAddress(forwardedFor: string | undefined, socketAddress: string): string {
  const hops = (forwardedFor ?? '').split(',').map(hop => hop.trim()).filter(hop => hop !== '')
  return hops.length > 0 ? hops[hops.length - 1]! : socketAddress
}

/**
 * Пределы для портальных экранов приложения.
 *
 * Выше публичных и считаются иначе: здесь не аноним с улицы, а сотрудник с подтверждённой
 * порталом сессией. Предел нужен не от него, а от того, что КАЖДЫЙ запрос сюда — это исходящий
 * вызов в портал клиента: проверка токена, чтение шаблонов, создание элемента. Похищенный
 * фреймовый токен живёт час, и без предела он превращается в усилитель нагрузки на чужой
 * портал. Нашла панель ревью PR #18.
 */
export const PORTAL_LIMITS = {
  perAddress: 120,
  perToken: 60,
} as const

/**
 * Ключ счётчика по порталу.
 *
 * Считаем по порталу, а не по сотруднику: нагрузка ложится на портал целиком, и десять
 * сотрудников одного клиента, дружно открывшие вкладку, — это десять вызовов в один
 * и тот же Битрикс24. `member_id` хешируется по той же причине, что и адрес: различать
 * порталы достаточно, знать их идентификаторы для счёта не нужно.
 */
export function portalKey(memberId: string, hash: (value: string) => string): string {
  return `rate:portal:${hash(memberId.trim().toLowerCase())}`
}
