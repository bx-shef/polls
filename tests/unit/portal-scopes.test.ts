import { describe, expect, it } from 'vitest'
import { missingScopes } from '../../server/domain/portals/scopes'

/**
 * Гвард под ловушку регистрации в партнёрском кабинете.
 *
 * `userfieldconfig.add` лежит в модуле `crm` и документируется в разделе CRM, а scope у него
 * СВОЙ — `userfieldconfig`. Выдать приложению один `crm` — самая естественная ошибка, и она
 * несимметрична по цене: `crm.type.add` пройдёт и создаст смарт-процесс, а следующий вызов
 * упадёт. На портале останется смарт-процесс без полей, при лимите 150 на весь портал.
 *
 * ⚠ Список ожидаемых разрешений записан здесь ВРУЧНУЮ, а не взят из `REQUIRED_SCOPES`.
 * Взятый оттуда, он расширялся бы вместе с ним и остался бы зелёным на любом изменении —
 * тест доказывал бы, что константа равна себе. В проекте этот класс дефекта уже ловили
 * дважды: подделка `getAuthData()`, повторившая опечатку кода, и список зон в тесте CSP.
 */

/** Ровно то, что надо отметить в кабинете. Сверено с документацией через `b24-dev-mcp`. */
const EXPECTED = ['crm', 'userfieldconfig', 'placement']

describe('разрешения приложения', () => {
  it('на полном наборе не требует ничего', () => {
    expect(missingScopes(EXPECTED)).toEqual([])
  })

  it('называет `userfieldconfig`, когда выдали только `crm`', () => {
    // Та самая ошибка: `crm` отмечен, поля создать нечем.
    expect(missingScopes(['crm', 'placement'])).toEqual(['userfieldconfig'])
  })

  it('не смущается лишними разрешениями', () => {
    // Портал отдаёт и базовые, и всё, что администратор отметил сверх нужного.
    expect(missingScopes([...EXPECTED, 'user', 'im', 'bizproc', 'log'])).toEqual([])
  })

  it('не считает отсутствием права регистр и пробелы', () => {
    // Строка разрешений приходит одним полем и режется нами; лишний пробел не должен
    // выглядеть как неотмеченная галочка в кабинете.
    expect(missingScopes([' CRM ', 'UserFieldConfig', 'PLACEMENT'])).toEqual([])
  })

  it('пустой список считает отсутствием всего, а не полным доступом', () => {
    // ⚠ Такое приходит, когда ответ сервера авторизации разобрался не до конца.
    // Трактовать это как «всё можно» значит пойти делать 17 вызовов вслепую.
    expect(missingScopes([])).toEqual(EXPECTED)
  })

  it('перечисляет всё недостающее разом', () => {
    // Иначе администратор правит кабинет по одной галочке за попытку установки.
    expect(missingScopes(['user'])).toEqual(EXPECTED)
  })
})
