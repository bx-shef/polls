-- Индекс под резолв ТЕНАНТА по токену приглашения (#47/#49).
--
-- ⚠️ Зачем отдельный, если уникальный уже есть. `uq_invitation_token_hash` составной —
-- `(portal_id, token_hash)`, — и его ведущая колонка `portal_id`. Пока по приглашению ходили только
-- `peek`/`consume`, портал был известен, и индекс подходил идеально (миграция `0005` это прямо
-- фиксирует). С мультитенантом появился ТРЕТИЙ читатель, и у него всё наоборот: он спрашивает
-- «чей это токен», то есть портала ещё не знает. Запрос `where token_hash = $1` этим индексом не
-- обслуживается и уходит в полный скан — на САМОМ горячем публичном пути (каждое открытие
-- `/s/:key?token=`, каждая проверка ссылки, каждая отправка ответа).
--
-- ⚠️ НЕ уникальный. Глобальную уникальность хеша даёт энтропия токена (`randomUUID`, 122 бита), а не
-- схема; уникальный индекс поверх живой базы мог бы упасть на миграции, а выигрыша сверх поиска не
-- даёт. Однозначность резолва обеспечивает вызывающий (`portalByInvitationToken`, `limit 1`).
--
-- Частичный (`where token_hash is not null`) — как и уникальный рядом: строки без хеша (наследие
-- схемы `0001`) этому читателю не интересны и в индексе не нужны.

-- ⚠️ Секции Down здесь НЕТ, как и у соседей: `applyMigrations` проигрывает ВЕСЬ каталог при каждом
-- старте контейнера, и `drop index` в этом же файле сносил бы индекс на каждом boot, стоит кому-то
-- задеть строку-маркер. Только добавление, только `if not exists`.
create index if not exists idx_invitation_token_hash
  on invitation (token_hash) where token_hash is not null;
