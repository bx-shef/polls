-- Снимок источника для миграции. Четыре запроса — четыре части снимка.
--
-- Это НЕ те же запросы, что в `audit-queries.sql`: там считалась фактура для проектирования
-- (распределения, доли, длины), здесь выгружаются сами данные. Снимок сохраняется файлом,
-- и миграция становится воспроизводимой: повторный прогон идёт по файлу, а не по живой базе.
--
-- Порядок выполнения важен только для запроса 4: он собирается по результату запроса 2.
--
-- Что с результатами делать: каждый запрос — одна таблица, выгрузить в JSON и положить
-- под именем из колонки «часть снимка». Адаптер (`server/domain/import/`) читает именно их.
--
-- | Часть снимка | Запрос | Что внутри                                   |
-- |--------------|--------|----------------------------------------------|
-- | `options`    | 1      | конфигурация анкет: секции, веса, диапазоны  |
-- | `fields`     | 2      | состав вопросов и их формулировки            |
-- | `cards`      | 3      | 247 карточек анкет со свойствами             |
-- | `answers`    | 4      | строки ответов из HL-таблиц                  |
--
-- ⚠ Идентификаторы свойств (362, 364, 365…) взяты из пачки 3 разбора и верны для ЭТОГО
-- портала. На другом портале они другие — перед выгрузкой сверить запросом из пачки 3.


-- ═══════════════════════════════════════════════════════════════════════════
-- Запрос 1 → `options`. Конфигурация анкет.
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Самая ценная часть: `questionary_list` — реестр типов, `questionary_group_<код>` — секции,
-- поля, веса `SIZE` и диапазоны интерпретации `TERMS`. Другого места с формой анкеты
-- в источнике нет.
--
-- ⚠ Выгружать ТЕКСТОМ, а не скриншотом: в одной ячейке лежит длинный JSON, и любое
-- усечение молча испортит структуру анкеты.

SELECT NAME AS name, VALUE AS value
FROM b_option
WHERE MODULE_ID = 'shef.questionary'
ORDER BY NAME;


-- ═══════════════════════════════════════════════════════════════════════════
-- Запрос 2 → `fields`. Состав вопросов и их формулировки.
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ⚠ Формулировок вопросов в конфигурации НЕТ: `NAME` там пустой у всех 119 полей.
-- Настоящий текст живёт только здесь, в подписях полей. Без этого запроса шаблоны
-- переносятся с пустыми заголовками.
--
-- `TABLE_NAME` вида `sh_qest_h_<код>` связывает поле с анкетой; `USER_TYPE_ID` (`double`
-- или `string`) — второй источник правды о типе вопроса рядом с `TYPE` из конфигурации,
-- и расхождение между ними стоит увидеть до импорта, а не после.

SELECT h.TABLE_NAME                     AS source_table,
       f.FIELD_NAME                     AS field,
       f.USER_TYPE_ID                   AS user_type,
       f.MANDATORY                      AS mandatory,
       f.MULTIPLE                       AS multiple,
       f.SORT                           AS sort,
       COALESCE(l.EDIT_FORM_LABEL, '')  AS title
FROM b_user_field f
JOIN b_hlblock_entity h ON f.ENTITY_ID = CONCAT('HLBLOCK_', h.ID)
LEFT JOIN b_user_field_lang l ON l.USER_FIELD_ID = f.ID AND l.LANGUAGE_ID = 'ru'
WHERE h.TABLE_NAME LIKE 'sh\_qest\_h\_%'
ORDER BY h.TABLE_NAME, f.SORT;


-- ═══════════════════════════════════════════════════════════════════════════
-- Запрос 3 → `cards`. Карточки анкет (инфоблок 67, 247 штук).
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Свойства разворачиваются в колонки с говорящими именами: в `b_iblock_element_prop_s67`
-- они называются `PROPERTY_<id>`, и работать с такими именами на стороне адаптера значит
-- размазать знание о чужой схеме по всему коду.
--
-- ⚠ Ловушка с датами, из-за которой поедет вся хронология отчётов: `SEND_DATE` (368),
-- вопреки названию, ставилось в момент ЗАПОЛНЕНИЯ. Настоящая дата отправки — `DATE_C_SEND`
-- (370). Поэтому колонки названы по смыслу, а не по имени свойства в источнике.
--
-- ⚠ `HASH` (371) не выгружается намеренно. Это предсказуемый `md5`, и воскрешать такие
-- ссылки нельзя: токен ссылки не меньше 128 бит, в хранилище только хеш — инвариант проекта.
--
-- Исторические баллы (365/366/367) выгружаются ТОЛЬКО для сверки в задаче 6. Записывать их
-- в портал нельзя: баллы пересчитываются по перенесённым ответам, иначе сверять нечего.

SELECT el.ID                                    AS id,
       el.DATE_CREATE                           AS created_at,
       el.TIMESTAMP_X                           AS changed_at,
       el.NAME                                  AS title,
       el.ACTIVE                                AS active,
       COALESCE(tp.XML_ID, '')                  AS type_code,
       COALESCE(st.XML_ID, '')                  AS status,
       COALESCE(ps.PROPERTY_363, '')            AS deal_id,
       COALESCE(ps.PROPERTY_395, '')            AS contact_id,
       COALESCE(ps.PROPERTY_372, '')            AS answers_row_id,
       ps.PROPERTY_370                          AS sent_at,
       ps.PROPERTY_368                          AS filled_at,
       ps.PROPERTY_365                          AS legacy_score_product,
       ps.PROPERTY_366                          AS legacy_score_process,
       ps.PROPERTY_367                          AS legacy_score_personal
FROM b_iblock_element el
JOIN b_iblock_element_prop_s67 ps ON ps.IBLOCK_ELEMENT_ID = el.ID
LEFT JOIN b_iblock_property_enum tp ON tp.ID = ps.PROPERTY_364
LEFT JOIN b_iblock_property_enum st ON st.ID = ps.PROPERTY_362
WHERE el.IBLOCK_ID = 67
ORDER BY el.ID;


-- ═══════════════════════════════════════════════════════════════════════════
-- Запрос 4 → `answers`. Строки ответов из двенадцати HL-таблиц.
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Имена таблиц и состав колонок заранее неизвестны, поэтому запрос не выгружает данные,
-- а ПИШЕТ SQL — тот же приём, что в пачках 6 и 7 аудита.
--
-- Порядок: выполнить этот запрос, получить столбец готовых строк, склеить их в один запрос
-- (у последней строки убрать хвостовой `UNION ALL`), выполнить второй раз. На выходе —
-- длинная таблица `source_table / row_id / field / value`, по одной строке на ответ.
--
-- Длинная форма, а не по колонке на вопрос, выбрана осознанно: 119 полей в 12 таблицах
-- не сводятся в одну ширину, а адаптеру всё равно нужна пара «код поля → значение».
--
-- ⚠ Пустая строка и NULL здесь — РАЗНЫЕ вещи, и ни одну нельзя превращать в ноль.
-- «Поставил ноль» и «не тронул ползунок» в источнике уже неразличимы, но добавлять к этому
-- ещё и потерю «вопроса не было» значит испортить сверку баллов окончательно.

SELECT CONCAT(
  'SELECT ''', h.TABLE_NAME, ''' AS source_table, ID AS row_id, ''',
  f.FIELD_NAME, ''' AS field, CAST(', f.FIELD_NAME, ' AS CHAR) AS value FROM ', h.TABLE_NAME,
  ' WHERE ', f.FIELD_NAME, ' IS NOT NULL UNION ALL'
) AS sql_text
FROM b_user_field f
JOIN b_hlblock_entity h ON f.ENTITY_ID = CONCAT('HLBLOCK_', h.ID)
WHERE h.TABLE_NAME LIKE 'sh\_qest\_h\_%'
ORDER BY h.TABLE_NAME, f.SORT;


-- ═══════════════════════════════════════════════════════════════════════════
-- Страховка перед выгрузкой: сошлись ли объёмы с разбором
-- ═══════════════════════════════════════════════════════════════════════════
--
-- Разбор источника обещает: 12 HL-таблиц, 119 полей (95 балльных + 24 текстовых),
-- 247 карточек, 295 строк ответов. Если цифры не сойдутся, данные изменились с момента
-- разбора — и прежде чем импортировать, надо понять, чем именно.

SELECT 'hlblocks' AS what, COUNT(*) AS cnt FROM b_hlblock_entity WHERE TABLE_NAME LIKE 'sh\_qest\_h\_%'
UNION ALL
SELECT 'fields', COUNT(*)
FROM b_user_field f
JOIN b_hlblock_entity h ON f.ENTITY_ID = CONCAT('HLBLOCK_', h.ID)
WHERE h.TABLE_NAME LIKE 'sh\_qest\_h\_%'
UNION ALL
SELECT 'cards', COUNT(*) FROM b_iblock_element WHERE IBLOCK_ID = 67
UNION ALL
SELECT 'options', COUNT(*) FROM b_option WHERE MODULE_ID = 'shef.questionary';
