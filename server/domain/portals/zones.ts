/**
 * Bitrix24 regional zones and the portal-domain check built on them.
 *
 * Список лежит в доменном слое, а не рядом с заголовками безопасности, потому что он нужен
 * дважды и по разным поводам: `frame-ancestors` в CSP разрешает встраивание, а проверка
 * домена при установке решает, стоит ли вообще разговаривать с этим порталом. Один список
 * на оба применения — иначе добавленная зона починит одно и молча оставит сломанным другое.
 */
export const BITRIX24_ZONES = [
  'ru',
  'by',
  'kz',
  'ua',
  'com',
  'eu',
  'de',
  'fr',
  'it',
  'es',
  'pl',
  'in',
  'jp',
  'vn',
  'mx',
  'id',
  'com.br',
  'com.tr',
] as const

/**
 * Зоны в шаблоне отсортированы от длинных к коротким.
 *
 * Формально это не нужно: якорь `$` заставил бы движок откатиться и попробовать `com.br`
 * после неудачной `com`. Но полагаться на порядок перебора в регулярке — значит объяснять
 * это каждому, кто её прочитает. Дешевле отсортировать.
 */
const zonePattern = [...BITRIX24_ZONES]
  .sort((a, b) => b.length - a.length)
  .map(zone => zone.replace(/\./g, '\\.'))
  .join('|')

/**
 * `<портал>.bitrix24.<зона>` — и ничего больше.
 *
 * Метка портала — один сегмент: у Битрикс24 не бывает `a.b.bitrix24.ru`, а разрешив
 * произвольную вложенность, мы приняли бы `bitrix24.ru.злоумышленник.tld` при малейшей
 * ошибке в якорях.
 */
const portalDomain = new RegExp(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\\.bitrix24\\.(?:${zonePattern})$`)

/**
 * Является ли строка доменом облачного портала Битрикс24.
 *
 * Проверяется при установке: `auth.domain` приходит из запроса, то есть от кого угодно,
 * пока не подтверждён `member_id`. Коробочные порталы сюда не проходят намеренно —
 * приложение живёт в Маркете, а Маркет ставится только в облако.
 *
 * Возвращает `boolean`, а не сужающий предикат `value is string`: с предикатом
 * отрицательная ветка `if (!isPortalDomain(host) || …)` сужала бы уже известную строку
 * до `never`, и следующая же проверка в той же строке переставала компилироваться.
 */
export function isPortalDomain(value: unknown): boolean {
  if (typeof value !== 'string') return false
  // Приводим регистр сами: флаг `i` заодно ослабил бы класс символов в метке портала.
  return portalDomain.test(value.toLowerCase())
}
