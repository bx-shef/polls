import { describe, expect, it } from 'vitest'
import { buildResultDescription } from '../../server/domain/answers/comment'
import type { SurveyTemplate } from '../../server/domain/surveys/model'
import { buildResultSections } from '../../server/domain/surveys/result-view'

/**
 * Описание дела с итогом — то, ради чего весь путь и затевался: менеджер открывает сделку
 * и видит, что ответил клиент. Здесь держится главное требование раздела 6 `docs/PROCESS.md`
 * — текст **не обрезается** — и то, что в описание не уезжает разметка, собранная из набранного
 * посторонним человеком.
 *
 * ⚠ С issue #84 (п. 6) баллы живут в блоках дела, а не в описании: их гварды переехали
 * в `activity-blocks.test.ts`. Здесь — слова клиента.
 */

const TEMPLATE: SurveyTemplate = {
  code: 'brand',
  title: 'Оценка работы по проекту',
  sections: [
    {
      key: 'product',
      title: 'Продукт',
      scored: true,
      bands: [{ from: 8, to: 10, text: 'Мы на вершине!' }],
      questions: [
        { key: 'P1', sourceKey: 'P1', title: 'Качество результата', type: 'scale', weight: 60, scored: true, scale: { min: 0, max: 10 } },
        { key: 'P2', sourceKey: 'P2', title: 'Соответствие задаче', type: 'scale', weight: 40, scored: true, scale: { min: 0, max: 10 } },
      ],
    },
    {
      key: 'open',
      title: 'Открытые вопросы',
      scored: false,
      bands: [],
      questions: [
        { key: 'T1', sourceKey: 'T1', title: 'Что понравилось', type: 'text', weight: 0, scored: false },
        { key: 'T2', sourceKey: 'T2', title: 'Что улучшить', type: 'text', weight: 0, scored: false },
      ],
    },
  ],
}

function description(answers: Record<string, number | string | null>) {
  return buildResultDescription(TEMPLATE, answers)
}

describe('описание дела с итогом', () => {
  it('не обрезает текст ответа', () => {
    // Требование раздела 6, и оно не про аккуратность: развёрнутый ответ и есть самое
    // ценное, что приносит опрос. Обрезав его до превью, мы оставим менеджеру ровно ту
    // бесполезную среднюю цифру, против которой написан весь проект.
    const long = 'Очень довольны. '.repeat(200)

    expect(description({ P1: 9, P2: 8, T1: long, T2: null })).toContain(long)
  })

  it('ГЛАВНОЕ: баллов в описании нет — они в блоках дела (решение владельца, п. 6)', () => {
    // Обратная мутация — вернуть сюда разделы с баллами — дала бы в деле цифры дважды:
    // простынёй в тексте и таблицей в блоках.
    const body = description({ P1: 9, P2: 8, T1: 'Всё отлично', T2: null })

    expect(body).not.toContain('8,6')
    expect(body).not.toContain('Продукт')
    expect(body).not.toContain('Качество результата')
    expect(body).not.toContain('Итоговый балл')
  })

  it('НЕ показывает текст диапазона — он написан для клиента, не для менеджера', () => {
    // ⚠ Гвард под замечание владельца: «откуда „Спасибо! Рады, что всё получилось“».
    // Это фраза, которую видит РЕСПОНДЕНТ на публичной странице.
    expect(description({ P1: 9, P2: 8, T1: 'Всё отлично', T2: null })).not.toContain('Мы на вершине!')
  })

  it('никогда не пусто: заголовок есть и у анкеты, на которую не ответили ничего', () => {
    // ⚠ Перезапись дела выпуска заменяет описание целиком — и только так адрес анкеты уходит
    // из ленты. Пустое описание оставило бы его там. Заодно «молчание тоже сигнал»: клиент
    // отправил пустую анкету, и в сделке это видно.
    expect(description({ P1: null, P2: null, T1: null, T2: null })).toBe('[B]Опрос пройден: Оценка работы по проекту[/B]')
  })

  it('не перечисляет незаполненные текстовые вопросы', () => {
    // Строка «— не ответил» на каждый пропуск превращает описание в перечень пустоты.
    const body = description({ P1: 9, P2: 8, T1: 'Всё отлично', T2: null })

    expect(body).toContain('Что понравилось')
    expect(body).not.toContain('Что улучшить')
  })

  it('пропускает текстовый ответ из одних пробелов', () => {
    // Респондент, стёрший текст перед отправкой, — обычное дело, и пустой блок
    // «Что улучшить:» в карточке выглядит поломкой. Нашла панель ревью PR #22.
    const body = description({ P1: 9, P2: 8, T1: 'Всё отлично', T2: '   ' })

    expect(body).toContain('Что понравилось')
    expect(body).not.toContain('Что улучшить')
  })

  it('обезвреживает разметку, пришедшую из ответа клиента', () => {
    // Гвард под находку панели ревью PR #22. Ссылка на анкету открыта постороннему человеку,
    // и его текст едет в карточку сделки, которую сотрудники клиента читают с доверием
    // к источнику: `[URL=…]Счёт на оплату[/URL]` выглядел бы там ссылкой, поставленной коллегой.
    const body = description({ P1: 9, P2: 8, T1: '[URL=http://чужой]Счёт на оплату[/URL]', T2: null })

    expect(body).not.toContain('[URL=')
    expect(body).not.toContain('[/URL]')
    // Текст при этом ЦЕЛ: обезвредили начертание скобок, а не выбросили слова.
    expect(body).toContain('Счёт на оплату')
    expect(body).toContain('http://чужой')
  })

  it('НАША разметка остаётся, разметка респондента — нет (issue #26)', () => {
    // ⚠ Вся защита держится на этой асимметрии, и проверять её надо одним утверждением:
    // лента разбирает описание дела как BB-код — замерено 25.09, причём НЕЗАВИСИМО
    // от объявленного `DESCRIPTION_TYPE`. Значит `[B]` в наших подписях — рабочая разметка,
    // и ровно поэтому такие же скобки из ответа постороннего человека обязаны приезжать
    // обезвреженными.
    const body = description({ P1: 9, P2: 8, T1: '[B]как будто заголовок[/B]', T2: null })

    expect(body).toContain('[B]')
    expect(body).toContain('как будто заголовок')
    expect(body).not.toContain('[B]как будто заголовок[/B]')
  })

  it('не обезвреживает формулировку вопроса — её писал сотрудник портала', () => {
    // Уровень доверия к тексту из шаблона тот же, что к самой CRM. Обезвреживать его значит
    // молча портить то, что сотрудник набрал осознанно.
    const withBrackets: SurveyTemplate = {
      ...TEMPLATE,
      sections: [
        TEMPLATE.sections[0]!,
        {
          ...TEMPLATE.sections[1]!,
          questions: [{ ...TEMPLATE.sections[1]!.questions[0]!, title: 'Что понравилось [важно]' }],
        },
      ],
    }

    expect(buildResultDescription(withBrackets, { P1: 9, P2: 8, T1: 'Всё' })).toContain('Что понравилось [важно]')
  })
})

describe('дата в деле', () => {
  /** Анкета с вопросом «Дата» — отдельно, чтобы не трогать ожидания тестов выше. */
  const DATED: SurveyTemplate = {
    ...TEMPLATE,
    sections: [{
      key: 'open',
      title: 'Открытые вопросы',
      scored: false,
      bands: [],
      questions: [{ key: 'D1', sourceKey: 'D1', title: 'Когда удобно связаться?', type: 'date', weight: 0, scored: false }],
    }],
  }

  it('пишет дату по-русски — той же записью, что виджет в карточке «Опроса»', () => {
    // ⚠ ГВАРД ПОД ДЕФЕКТ issue #84, п. 13. Виджет в карточке переводил `2026-09-28`
    // в `28.09.2026`, а дело в ленте печатало строку с провода как есть: одно прохождение
    // в двух местах выглядело двумя разными датами. Сверяем не с литералом, а с самим
    // виджетом — чтобы разойтись им было нельзя, даже поменяв запись в одном месте.
    const body = buildResultDescription(DATED, { D1: '2026-09-28' })
    const card = buildResultSections(DATED, { D1: '2026-09-28' }, new Map())[0]!.answers[0]!.value

    expect(card).toBe('28.09.2026')
    expect(body).toContain(card)
    expect(body).not.toContain('2026-09-28')
  })

  it('дату, принятую до календаря, пишет как есть — и обезвреживает, как любой ответ', () => {
    // До календаря на публичной странице вопрос «Дата» был текстовым полем, и в буфере
    // могут лежать такие ответы. Выбросить их нельзя, выдать за дату — тем более,
    // а разметка из них не должна ожить в чужой CRM, как и из любого текста.
    const body = buildResultDescription(DATED, { D1: '[URL=http://чужой]в пятницу[/URL]' })

    expect(body).toContain('в пятницу')
    expect(body).not.toContain('[URL=')
  })
})
