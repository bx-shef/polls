/**
 * The intermediate format every import source is normalized into.
 *
 * Между источником и записью в портал стоит один формат — не потому, что источников много
 * (сегодня он ровно один), а потому, что без него сверка баллов из задачи 6 упирается
 * в структуру чужой базы. Пересчёт должен читать наш формат, а не `b_option`.
 *
 * Здесь только типы и коды предупреждений. Разбор конкретного источника — в соседних файлах,
 * запись в портал — в интеграции: домен не знает ни про MySQL, ни про REST.
 */

/** Тип вопроса в нормализованном виде. Осей две, и они независимы: виджет и метрика. */
export type ImportedQuestionType = 'scale' | 'text' | 'date'

/**
 * Что не перенеслось буквально.
 *
 * Предупреждение — не ошибка: импорт продолжается, но каждый случай попадает в отчёт о переносе.
 * Отчёт — часть услуги, а не бонус, и клиент должен узнать об искажениях ДО записи, а не после.
 *
 * | Код | Что случилось |
 * |---|---|
 * | `question-split` | вопрос стоял в двух секциях с разными весами — ключ расщеплён |
 * | `zero-weight` | вес `0` означал «не идёт в оценку» — стал явным флагом |
 * | `date-as-text` | тип `DATE` перенесён текстом в ISO: типа даты в новой модели нет |
 * | `html-stripped` | текст интерпретации хранился готовым HTML — вычищен до текста |
 * | `weights-not-100` | сумма весов в секции не даёт 100 |
 * | `band-gap` | диапазоны интерпретации не покрывают шкалу без дыр |
 * | `section-not-scored` | секция без единого вопроса, идущего в оценку |
 * | `template-unreadable` | конфигурация анкеты не разобралась: шаблон пропущен целиком |
 */
export type ImportWarningCode
  = | 'question-split'
    | 'zero-weight'
    | 'date-as-text'
    | 'html-stripped'
    | 'weights-not-100'
    | 'band-gap'
    | 'section-not-scored'
    | 'template-unreadable'

export interface ImportWarning {
  code: ImportWarningCode
  /** Код шаблона, к которому относится предупреждение. */
  template: string
  /** Секция или вопрос — чтобы в отчёте было видно, где именно. */
  at: string
  /** Человеческое объяснение по-русски: отчёт читает клиент, а не разработчик. */
  detail: string
}

/** Диапазон интерпретации: границы включительно и текст, который увидит респондент. */
export interface ImportedBand {
  from: number
  to: number
  /** Уже вычищенный от HTML текст. Разметку мы не храним — см. `docs/PROCESS.md`, раздел 7. */
  text: string
}

export interface ImportedQuestion {
  /**
   * Ключ вопроса внутри версии шаблона. Уникален — это инвариант проекта.
   *
   * Обычно совпадает с кодом `UF_*` источника. Расходится в одном случае: вопрос стоял
   * в двух секциях сразу, и второе вхождение получило суффикс секции.
   */
  key: string
  /**
   * Код поля в источнике, по которому берётся значение ответа.
   *
   * ⚠ При расщеплении два разных `key` указывают на ОДИН `sourceKey`, и обоим при пересчёте
   * отдаётся одно значение — только так баллы сходятся с историческими.
   */
  sourceKey: string
  /** Формулировка. В источнике её нет в конфигурации — она лежит подписями полей. */
  title: string
  type: ImportedQuestionType
  /** Вес внутри секции, из `SETTING.SIZE`. */
  weight: number
  /** Идёт ли вопрос в оценку. Вес `0` в источнике означал именно это. */
  scored: boolean
  /** Границы шкалы — только у балльных вопросов. */
  scale?: { min: number, max: number }
}

export interface ImportedSection {
  /** Ключ секции: `product`, `process`, `personal`, `open`. */
  key: string
  title: string
  /**
   * Даёт ли секция балл.
   *
   * В источнике признаком было непустое `FIELD` — имя свойства карточки, куда писался балл
   * секции. Пустое `FIELD` — секция открытых вопросов, балла у неё нет.
   */
  scored: boolean
  questions: ImportedQuestion[]
  bands: ImportedBand[]
}

export interface ImportedTemplate {
  /** Код опроса: `brand`, `game`, `digital`, … Он же часть внешнего ключа идемпотентности. */
  code: string
  title: string
  sections: ImportedSection[]
}

/** Результат разбора: то, что переносим, и то, о чём обязаны сказать. */
export interface ImportedTemplates {
  templates: ImportedTemplate[]
  warnings: ImportWarning[]
}
