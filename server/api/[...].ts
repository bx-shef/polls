/**
 * 404 for anything under `/api/` that no handler claims.
 *
 * Без этого маршрута несуществующий адрес под `/api/` попадал в SPA-правило `/**` и отвечал
 * **200 и HTML-страницей** — проверено на боевом домене. Для приложения Битрикс24 это дорого
 * вдвойне:
 *
 * 1. Адрес обработчика событий мы вписываем в карточку приложения руками. Опечатка в нём
 *    выглядела бы как исправный обработчик: портал видит 200 и считает установку принятой,
 *    а на деле не принимает её никто. Ошибку такого рода ищут долго, потому что «сервер
 *    отвечает».
 * 2. Страница при этом отдавалась с политикой для `/api/**` (`default-src 'none'`), то есть
 *    была заведомо нерабочей: собственные скрипты она загрузить не может.
 *
 * Nitro предпочитает конкретный маршрут catch-all, поэтому существующие обработчики
 * этот файл не перехватывает.
 */
export default defineEventHandler((event) => {
  throw createError({
    statusCode: 404,
    statusMessage: 'Not found',
    // Без этого Nitro отдал бы HTML-страницу ошибки; под `/api/` ждут JSON.
    data: { path: event.path },
  })
})
