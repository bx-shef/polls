/**
 * Ссылка на прохождение опроса по приглашению — ОДНА точка правды об её форме.
 *
 * Раньше форма жила в двух несвязанных местах: сборка (`?token=` строкой в роуте виджета) и всё,
 * что о ней рассказывали комментарии. Пока читателя не было, расхождение не проявлялось; с
 * подключением токена к странице оно стало бы двухсторонним и молчаливым — выписали с одним именем
 * параметра, прочитали другое, и ответ пишется без привязки к сделке, ничем этого не показывая.
 *
 * Лежит в `client/`, потому что нужен обеим сторонам: `server/` собирает ссылку, `app/` её читает.
 * `~core/api` и `~core/bitrix24` клиенту импортировать нельзя (граница `~core`), а `~core/client` —
 * можно.
 */

/** Имя query-параметра с токеном приглашения. */
export const INVITATION_TOKEN_PARAM = 'token'

/**
 * Путь прохождения опроса. Без домена: базовый URL знает только сервер (`APP_DOMAIN`/`DOMAIN`), а
 * клиенту он не нужен — он и так на этом домене.
 */
export function surveyPath(surveyKey: string, token?: string): string {
  const path = `/s/${encodeURIComponent(surveyKey)}`
  return token ? `${path}?${INVITATION_TOKEN_PARAM}=${encodeURIComponent(token)}` : path
}

/**
 * Токен из query-параметров страницы.
 *
 * ⚠️ Принимает `unknown`, а не строку, намеренно: у роутера значение query — `string | string[] |
 * null | undefined`, и `?token=a&token=b` даёт массив. Молча взять первый элемент значило бы
 * позволить отправителю ссылки подсунуть второй токен, который увидит не человек, а только код.
 * Массив отвергаем целиком.
 *
 * Пустую строку и пробельный мусор приводим к `undefined` — «токена нет» и «токен пустой» для
 * вызывающего одно и то же, и различать их значило бы плодить ветку без разницы в поведении.
 */
export function readInvitationToken(raw: unknown): string | undefined {
  if (typeof raw !== 'string') return undefined
  const token = raw.trim()
  return token.length > 0 ? token : undefined
}
