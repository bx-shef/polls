/**
 * Потолок размера тела запроса — общий бэкстоп для ВСЕХ роутов.
 *
 * **Зачем отдельный слой, если у роутов уже есть свои капы.** Капы у роутов расставлены поимённо, и
 * это ровно тот способ, которым дыра появляется незаметно: новый роут пишется по образцу соседнего,
 * строчку с проверкой в образец скопировать забывают, и он уходит в прод без ограничения. Так и вышло:
 * из восьми роутов, читающих тело, кап был у четырёх, и все четыре незакрытых читали тело **до**
 * подтверждения вызывающего — три публичных вебхука Bitrix24 (`/api/b24/install`, `/api/b24/deal-update`,
 * `/api/b24/robot`) до сверки токена и `/api/b24/deal-invite` до проверки фрейма. Значит, отправитель,
 * знающий адрес, мог бы занять память процесса, ничего о портале не зная. Здесь проверка не «ещё одна
 * такая же», а **последняя**: она стоит перед маршрутизацией и действует на то, что автор роута забыл.
 *
 * **Почему заголовки, а не подсчёт байтов на лету.** У h3 `readBody` буферизует тело целиком и своего
 * ограничения не имеет, поэтому отказать нужно ДО чтения — иначе тело уже в памяти. Единственное, что
 * известно до чтения, — заявленная длина. (Ядровой демо-сервер `src/server/node.ts` считает байты
 * потоково и в ветке 411 не нуждается — она следствие устройства h3, а не общего закона.) Отсюда:
 *  - есть любой `Transfer-Encoding` → **411**: размер не заявлен, проверять нечего. Это и был обход —
 *    `Number(undefined ?? 0)` даёт `0`, то есть у поимённых капов chunked-тело проходило как «нулевое»
 *    (у трёх из четырёх; в `/api/feedback` эта ветка уже стояла — она и стала образцом).
 *    Отвечать 411 законно: RFC 9110 §15.5.12 ровно про «сервер требует заявленной длины»;
 *  - длина заявлена и больше потолка → **413**;
 *  - ни того, ни другого → тела нет, пропускаем.
 *
 * Клиенты от этого не страдают: `fetch`/`XMLHttpRequest` со строковым телом всегда ставят
 * `Content-Length`, а Bitrix24 шлёт события обычной form-urlencoded с длиной. На проде перед
 * приложением вдобавок стоит nginx-proxy с `proxy_request_buffering on` — он всегда предъявляет
 * длину наверх, так что ветка 411 там практически недостижима и работает для прямых деплоев
 * (коробка, self-hosted, dev).
 *
 * Чистая функция: ни h3, ни `process.env` — решение проверяется юнит-тестами, h3-слой остаётся тонким.
 */

/**
 * Общий потолок — **128 КБ**. Величина зажата с двух сторон, и обе границы измерены, а не выбраны на глаз.
 *
 * **Снизу: строго больше самого большого поимённого капа** (64 КБ у `/api/submit` и у публикации версии).
 * Равенство здесь — тихая поломка диагностики: бэкстоп срабатывал бы первым, и человек вместо «сократите
 * ответ» получал бы общее «сократите содержимое», а роутовое сообщение стало бы мёртвым кодом. Задача
 * бэкстопа — не подпустить к исчерпанию памяти; ЧТО считать допустимым телом, решает роут.
 *
 * **Сверху: столько, сколько не жалко удержать в памяти одновременно.** Отказ по заголовку дёшев, но
 * тело, которое в потолок УКЛАДЫВАЕТСЯ, буферизуется целиком, и висящих запросов может быть много.
 * Замер на собранном приложении: ~58 КБ RSS на один запрос в полёте при капе 64 КБ. У `/api/b24/install`
 * `readBody` стоит **первой** строкой — раньше собственного лимитера, — поэтому там бэкстоп единственная
 * защита; при капе 1 МБ четыреста подвисших соединений удержали бы сотни мегабайт, а `mem_limit` у
 * контейнера не задан. 128 КБ оставляют тот же порядок величины, что и раньше, и одновременно
 * освобождают роутам их собственные сообщения.
 *
 * ⚠️ На проде перед приложением стоит **общий** `nginx-proxy` с дефолтом `client_max_body_size 1m`.
 * Наш потолок намеренно жёстче: прокси делится со всеми проектами хоста, и поднятый там ради чужого
 * приложения лимит молча поднял бы потолок и нам.
 *
 * Инвариант «ни один роут не объявляет кап больше этого» закреплён тестом: кап сверх бэкстопа —
 * обещание, которого роут не может выполнить.
 */
export const MAX_REQUEST_BODY_BYTES = 128 * 1024

/** Заголовки, по которым принимается решение. */
export const CONTENT_LENGTH_HEADER = 'content-length'
export const TRANSFER_ENCODING_HEADER = 'transfer-encoding'

export interface BodyLimitInput {
  /** Значение `Content-Length` как пришло (может отсутствовать). */
  contentLength?: string | undefined
  /** Значение `Transfer-Encoding` как пришло (`chunked` и т. п.). */
  transferEncoding?: string | undefined
  /** Потолок в байтах; по умолчанию {@link MAX_REQUEST_BODY_BYTES}. */
  limit?: number
}

/** Отказ: статус и текст для пользователя. `null` — тело допустимо (или его нет). */
export interface BodyLimitRejection {
  status: 411 | 413
  error: string
}

/**
 * Разобрать `Content-Length`.
 *
 * Принимаем ТОЛЬКО десятичное целое без знака. `Number()` слишком либерален: он проглотит `1e9`,
 * ` 12 `, `0x10` и пустую строку (даёт `0`) — а по каждой из этих форм заявленная длина расходится с
 * тем, что реально приедет. Расхождение здесь опаснее обычной опечатки: это классическая почва для
 * подмешивания второго запроса в поток (request smuggling), и правильная реакция — не угадывать, а
 * считать длину незаявленной.
 */
function parseContentLength(raw: string | undefined): number | null {
  if (raw === undefined) return null
  const s = raw.trim()
  if (!/^\d+$/.test(s)) return null
  const n = Number(s)
  return Number.isSafeInteger(n) ? n : null
}

/**
 * Есть ли у запроса тело и допустимо ли оно.
 *
 * Метод намеренно НЕ учитывается. Гейт по списку `POST|PUT|PATCH` — это ещё одно место, где можно
 * ошибиться, и обходится он сменой глагола; а решение и без метода однозначно: нет ни длины, ни
 * `Transfer-Encoding` — значит нет и тела, и обычный GET проходит здесь без единой аллокации.
 */
export function bodyLimitStatus(input: BodyLimitInput): BodyLimitRejection | null {
  const limit = input.limit ?? MAX_REQUEST_BODY_BYTES

  // `Transfer-Encoding` СТАРШЕ `Content-Length` — так требует RFC 9112 §6.3, и это не буквоедство:
  // пара «оба заголовка сразу» и есть каноническая форма подмешивания второго запроса в поток
  // (CL.TE-смаглинг). Доверившись здесь длине, мы пропустили бы `Content-Length: 0` с настоящим
  // chunked-телом следом. Сегодня до нас такой запрос не доходит — парсер Node отвергает пару сам
  // (`HPE_INVALID_TRANSFER_ENCODING`, проверено). Но это свойство ЧУЖОГО парсера, а функция чистая и
  // переиспользуемая: правильный порядок стоит одну строку и не зависит от того, кто нас вызывает.
  const te = (input.transferEncoding ?? '').trim()
  if (te !== '') {
    return { status: 411, error: 'Не удалось принять запрос: не указан размер данных. Повторите отправку.' }
  }

  const declared = parseContentLength(input.contentLength)
  if (declared !== null) {
    if (declared > limit) {
      return { status: 413, error: 'Слишком большой объём данных. Сократите содержимое и повторите.' }
    }
    return null
  }

  // Ни `Transfer-Encoding`, ни разбираемой длины. Заголовка длины нет вовсе — тела нет, пропускаем.
  if (input.contentLength === undefined) return null

  // Длина заявлена, но в форме, которой нельзя верить: проверить размер до чтения невозможно,
  // поэтому отказываем, а не «пропускаем на всякий случай».
  return { status: 411, error: 'Не удалось принять запрос: не указан размер данных. Повторите отправку.' }
}
