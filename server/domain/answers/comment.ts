import type { AnswerValue } from '../surveys/answer'
import type { SurveyTemplate } from '../surveys/model'
import type { SectionScore, SurveyScore } from '../surveys/scoring'

/**
 * Builds the text a manager reads in the deal's timeline.
 *
 * Это то место, ради которого весь путь и затевался: менеджер открывает сделку и видит,
 * что ответил клиент. Не превью, не «оценка 7», а балл и текст целиком.
 *
 * ⚠ Текст **не обрезается** — это требование `docs/PROCESS.md`, раздел 6, и оно не про
 * аккуратность. Развёрнутый ответ клиента и есть самое ценное, что приносит опрос; обрезав
 * его до превью, мы оставим менеджеру ровно ту бесполезную среднюю цифру, против которой
 * написан весь проект.
 *
 * ⚠ Текст собирается ПЛОСКИМ, без разметки. Таймлайн Битрикс24 понимает и BB, и HTML,
 * и соблазн выделить заголовки жирным велик — но в текст попадает то, что набрал посторонний
 * человек, и строить из этого разметку значит отдать ему управление вёрсткой записи в чужой
 * CRM. Разделители здесь наши и не собираются из ответов.
 *
 * ⚠ Носитель теперь — ДЕЛО, а не комментарий: `crm.timeline.comment.add` не идемпотентен,
 * и повтор доставки добавлял бы второй комментарий. См. `timeline-activity.ts`. Там же
 * выставляется `DESCRIPTION_TYPE = 2` (BB-код) — значение снято с живого портала методом
 * `crm.enum.contenttype`, а не взято из памяти.
 *
 * ⚠ Здесь стояло «`DESCRIPTION_TYPE = 1` (простой текст)», и это было неправдой с того дня,
 * как владелец попросил блоки: код ставит двойку, а заголовки разделов собираются `[B]…[/B]`
 * прямо в этом файле. Разбор issue #26 её и поймал — ровно тот случай, о котором он заведён:
 * «в коде живёт факт, который никто не проверял».
 *
 * ⚠ Этого мало, и первая версия на этом и остановилась. Не строить разметку самим — полдела;
 * вторая половина в том, что её может построить ОТВЕТИВШИЙ. Ссылка на анкету открыта
 * постороннему неаутентифицированному человеку, а его текст едет в карточку сделки, которую
 * сотрудники клиента читают с доверием к источнику. `[URL=…]Счёт на оплату[/URL]` выглядел бы
 * там обычной ссылкой, поставленной коллегой. Поэтому в тексте респондента квадратные скобки
 * обезвреживаются — см. `neutralizeMarkup`. Нашла панель ревью PR #22.
 */

/** Разделитель разделов: наш, из ответа клиента не собирается. */
const RULE = '———'

/** Выделить свой текст жирным. Собирается ТОЛЬКО из наших строк — см. `neutralizeMarkup`. */
const bold = (text: string) => `[B]${text}[/B]`

/**
 * Собрать текст.
 *
 * Возвращает пустую строку, если писать нечего вовсе: портал отвергает пустое описание,
 * и вызывающий обязан это проверить, а не отправлять вслепую.
 */
export function buildAnswerComment(
  template: SurveyTemplate,
  answers: Record<string, AnswerValue>,
  score: SurveyScore,
): string {
  const lines: string[] = [bold(`Опрос пройден: ${template.title}`)]

  const scores = new Map(score.sections.map(s => [s.key, s]))

  for (const section of template.sections) {
    const parts = sectionLines(section, answers, scores.get(section.key))
    if (parts.length === 0) continue
    lines.push('', RULE, ...parts)
  }

  if (score.overall !== null) {
    lines.push('', RULE, bold(`Итоговый балл: ${format(score.overall)}`))
  }

  // Заголовок один, без единого раздела с содержимым, — это не запись, а шум.
  return lines.length > 1 ? lines.join('\n') : ''
}

function sectionLines(
  section: SurveyTemplate['sections'][number],
  answers: Record<string, AnswerValue>,
  score: SectionScore | undefined,
): string[] {
  // ⚠ Сначала собираем ответы, и только потом решаем про заголовок раздела. Иначе раздел,
  // в котором не заполнено ничего, печатает свою шапку и больше ничего — а пустой заголовок
  // в карточке выглядит поломкой, не данными.
  const body: string[] = []

  for (const question of section.questions) {
    const value = answers[question.key]

    if (question.type === 'scale') {
      // ⚠ Балл КАЖДОГО вопроса, а не только средний по разделу. Первая редакция показывала
      // один агрегат, и менеджер видел «Результат: 9», не зная, что за ним 10 и 8. Смотреть
      // ради этого в поле «Ответы (JSON)» — не работа человека. Нашёл владелец: «у нас
      // 2 вопроса и 1 комментарий, в деле такого не видно».
      if (typeof value !== 'number') continue
      const max = question.scale === undefined ? '' : ` из ${format(question.scale.max)}`
      body.push(`${label(question.title)} ${format(value)}${max}`)
      continue
    }

    // Незаполненный текстовый вопрос не показываем: строка «— не ответил» на каждый
    // пропущенный вопрос превращает запись в перечень пустоты.
    if (typeof value !== 'string' || value.trim() === '') continue

    // Формулировка вопроса не обезвреживается: её писал сотрудник портала, у неё тот же
    // уровень доверия, что у самой CRM. Обезвреживается ровно то, что набрал посторонний.
    body.push('', label(question.title), neutralizeMarkup(value))
  }

  const scored = score !== undefined && score.score !== null
  // ⚠ Оцениваемый раздел говорит о себе ВСЕГДА, даже когда в нём не ответили ни на что:
  // «без оценки» — это сигнал, а молчание неотличимо от «раздела не было». Молчит только
  // неоцениваемый раздел, в котором нечего показать.
  if (!scored && !section.scored && body.length === 0) return []

  const head: string[] = []
  if (scored) {
    const partial = score!.answered < score!.scored
      // ⚠ Неполноту показываем словами. Балл, посчитанный по двум вопросам из пяти, выглядит
      // точно так же, как посчитанный по пяти, — и менеджер сравнил бы несравнимое.
      ? ` (по ${score!.answered} из ${score!.scored} вопросов)`
      : ''
    head.push(bold(`${section.title}: ${format(score!.score!)}${partial}`))
  }
  else if (section.scored) {
    head.push(bold(`${section.title}: без оценки — ни один вопрос не заполнен`))
  }
  else if (section.title !== '') {
    head.push(bold(section.title))
  }

  // ⚠ Текст интерпретации (`score.band.text`) СЮДА НЕ ПОПАДАЕТ, и это исправление.
  // Он написан, чтобы сказать его КЛИЕНТУ на публичной странице: «Спасибо! Рады, что всё
  // получилось». В карточке сделки менеджер читал эту фразу как сообщение себе и справедливо
  // спрашивал, откуда она взялась. Нашёл владелец на живом прогоне.

  // Пустая строка между шапкой и первым ответом не нужна: `body` её уже несёт у текстовых.
  return [...head, ...(head.length > 0 && body[0] === '' ? body.slice(1) : body)]
}

/** Подпись вопроса жирным. Двоеточие не приписываем к тому, что и так кончается знаком. */
function label(title: string): string {
  return bold(/[?!:.]$/.test(title) ? title : `${title}:`)
}

/** Балл в русской записи: запятая, а не точка, и без хвостовых нулей. */
function format(score: number): string {
  return String(score).replace('.', ',')
}

/**
 * Обезвредить разметку в тексте, который набрал респондент.
 *
 * ⚠ Скобки ЗАМЕНЯЮТСЯ на полноширинные, а не вырезаются. Текст ответа не обрезается и не
 * теряется — это требование раздела 6, — он остаётся читаемым целиком, просто перестаёт быть
 * разметкой. Из всех способов этот единственный не делает текст хуже: вырезание крадёт символы,
 * невидимый разделитель внутри скобок ломает копирование, а экранирования у BB-кода нет.
 *
 * ⚠ УГЛОВЫЕ СКОБКИ ТОЖЕ. Заведено панелью ревью PR #37–#39 из опасения, что портал
 * по умолчанию подставит HTML (`3`). В этой форме опасение замером не подтвердилось:
 * по умолчанию портал ставит `2` (BB-код).
 *
 * ⚠ Но 25.09 замерено то, что переворачивает рассуждение целиком: **лента разбирает BB-код
 * независимо от объявленного типа описания**. Два дела с одинаковым текстом и типами `1`
 * и `2` нарисованы одинаково — жирным и кликабельной ссылкой. Значит рассуждать «сейчас тип
 * такой-то, поэтому разметка не оживёт» нельзя вообще: поле, по которому рассуждали, разбором
 * не управляет.
 *
 * Отсюда вес этой функции: она — ЕДИНСТВЕННОЕ, что стоит между текстом постороннего человека
 * и разметкой в карточке клиента. Про угловые скобки такого замера пока нет, и ровно поэтому
 * они обезвреживаются тоже: цена защиты — четыре символа начертания в тексте, который их почти
 * никогда не содержит, а цена ошибки — `<img src=x onerror=…>` от постороннего человека,
 * живущий в чужой CRM навсегда.
 */
export function neutralizeMarkup(text: string): string {
  return text
    .replaceAll('[', '［')
    .replaceAll(']', '］')
    .replaceAll('<', '＜')
    .replaceAll('>', '＞')
}
