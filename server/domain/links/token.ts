import { createHash, randomBytes, timingSafeEqual } from 'node:crypto'

/**
 * Survey link tokens: how they are minted and how they are stored.
 *
 * Токен — единственный ключ доступа к чужой анкете, поэтому требования к нему записаны
 * инвариантом: не меньше 128 бит случайности, в хранилище только хеш, TTL и одноразовость.
 *
 * Как было в разобранном решении заказчика: `md5(ID элемента + '_' + ID сделки)`. Зная пару
 * идентификаторов, чужую анкету открывали перебором — ни TTL, ни одноразовости, а в шапке
 * шаблона стоял `<meta name="robots" content="all">`. Это не гипотетический риск, а то,
 * что уже работало у клиента.
 */

/**
 * Длина токена в байтах.
 *
 * 256 бит, вдвое больше требуемого инвариантом минимума. Цена запаса — 43 символа в адресе
 * вместо 22, и это ровно та цена, которую стоит платить: удлинить токен на выданных ссылках
 * потом нельзя, а укоротить никто и не попросит.
 */
const TOKEN_BYTES = 32

/** Длина hex-хеша SHA-256. По ней узнаётся, что в колонке лежит хеш, а не сам токен. */
const HASH_HEX_LENGTH = 64

/**
 * Форма токена в адресе: base64url без набивки.
 *
 * Без набивки — чтобы в ссылке не было `=`, который часть почтовых клиентов и мессенджеров
 * ломает при автоопределении границы ссылки. Алфавит `A–Z a–z 0–9 - _` безопасен и в пути
 * адреса, и при копировании руками.
 */
const TOKEN_PATTERN = /^[A-Za-z0-9_-]{43}$/

/** Выпустить новый токен. Возвращается только здесь и только один раз — дальше живёт хеш. */
export function mintToken(): string {
  return randomBytes(TOKEN_BYTES).toString('base64url')
}

/**
 * Хеш токена для хранения и поиска.
 *
 * SHA-256 без соли и без растягивания — намеренно. Соль сделала бы поиск по хешу невозможным
 * (искать пришлось бы перебором всех ссылок), а растягивание здесь не нужно: токен не пароль,
 * у него 256 бит настоящей случайности, и перебор по словарю к нему неприменим.
 */
export function hashToken(token: string): string {
  return createHash('sha256').update(token, 'utf8').digest('hex')
}

/**
 * Похоже ли это на наш токен.
 *
 * Дешёвая проверка ДО обращения к базе: она отсекает перебор по коротким и кривым значениям,
 * не тратя на него запрос. Совпадение формы ничего не доказывает — доказывает только хеш.
 */
export function isTokenShaped(token: string): boolean {
  return TOKEN_PATTERN.test(token)
}

/**
 * Сравнить два хеша за постоянное время.
 *
 * Обычное `===` на строках выходит из сравнения на первом различии, и по времени ответа
 * можно восстанавливать хеш по байту. Здесь это скорее гигиена, чем горящая дыра — искать
 * мы всё равно будем индексом по колонке, — но там, где сравнение секрета всё-таки пишется
 * руками, оно должно быть постоянным по времени.
 */
export function hashesEqual(left: string, right: string): boolean {
  if (left.length !== HASH_HEX_LENGTH || right.length !== HASH_HEX_LENGTH) return false
  return timingSafeEqual(Buffer.from(left, 'hex'), Buffer.from(right, 'hex'))
}
