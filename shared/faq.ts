/**
 * Текст `llms.txt` — та же справка, что и на странице, простым текстом.
 *
 * Базовый адрес — канонический адрес сайта. Пусто — ссылок в тексте нет вовсе: относительная
 * ссылка в документе, который читает чужой помощник, ведёт в никуда.
 */
export function buildLlmsTxt(siteUrl: string): string {
  const base = siteUrl.trim().replace(/\/+$/, '')
  const lines: string[] = ['# Опросы клиентов для Битрикс24', '', FAQ_INTRO, '']
  if (base !== '') lines.push(`Сайт: ${base}/`, `Справка: ${base}/help`, '')
  lines.push('## Как отвечать пользователю', '', FAQ_AGENT_PROMPT, '', '## Вопросы и ответы', '')
  for (const entry of FAQ) {
    lines.push(`### ${entry.question}`, '')
    for (const paragraph of entry.answer) lines.push(paragraph, '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}
