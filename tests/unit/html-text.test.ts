import { describe, expect, it } from 'vitest'
import { htmlToText, looksLikeHtml } from '../../server/domain/import/html-text'

/**
 * Тексты интерпретации в источнике лежат готовой вёрсткой с классами `landing24`. Мы храним
 * текст, а не разметку, — значит при импорте их надо вычистить, не склеив слова и не потеряв
 * абзацы. Функция готовит данные к сохранению; защита от XSS — на своём парсере при показе.
 */

describe('вычистка HTML до текста', () => {
  it('убирает теги, сохраняя слова', () => {
    expect(htmlToText('<p class="g-color-white g-font-size-16 text-center">Мы на <b>вершине</b>!</p>'))
      .toBe('Мы на вершине!')
  })

  it('не склеивает абзацы в одно слово', () => {
    // Вырезать теги раньше, чем расставить переводы строк, — и «тудаМы» станет одним словом.
    // Абзацы разделяются пустой строкой: закрывающий и открывающий тег дают по переводу.
    expect(htmlToText('<p>Где-то мы свернули не туда</p><p>Мы на вершине</p>'))
      .toBe('Где-то мы свернули не туда\n\nМы на вершине')
  })

  it('превращает перенос строки в перенос, а не в пустоту', () => {
    expect(htmlToText('первая<br>вторая')).toBe('первая\nвторая')
  })

  it('разбирает сущности, которые встречаются в этих текстах', () => {
    expect(htmlToText('&laquo;Шеф&raquo; &mdash; это&nbsp;мы &amp; вы')).toBe('«Шеф» — это мы & вы')
  })

  it('разбирает числовые сущности в обеих формах', () => {
    expect(htmlToText('&#1064;&#x435;&#x444;')).toBe('Шеф')
  })

  it('оставляет как есть то, чего не знает', () => {
    // Подставлять «замещающий символ» значит тихо испортить текст, который потом читает человек.
    expect(htmlToText('&неизвестная; &#999999999;')).toBe('&неизвестная; &#999999999;')
  })

  it('сводит пробелы внутри строки и лишние пустые строки', () => {
    expect(htmlToText('<p>много     пробелов</p><p></p><p></p><p>и абзацев</p>'))
      .toBe('много пробелов\n\nи абзацев')
  })

  it('не падает на пустом входе и на тексте без разметки', () => {
    expect(htmlToText('')).toBe('')
    expect(htmlToText('просто текст')).toBe('просто текст')
  })

  it('разбирает сущности ПОСЛЕ вырезания тегов, а не до', () => {
    // Гвард от «улучшения», найденного панелью ревью PR #14. Порядок не случайный:
    // экранированный `&lt;script&gt;` на выходе остаётся ТЕКСТОМ `<script>` — и это правильно,
    // безопасность обеспечивает экранирующий парсер при показе, а не эта функция.
    // Обратный порядок хуже: легитимное `Оценка &lt; 5` раскроется в `<` до вырезания
    // и склеится с ближайшим `>` дальше по тексту, съев кусок содержимого.
    expect(htmlToText('&lt;script&gt;alert(1)&lt;/script&gt;')).toBe('<script>alert(1)</script>')
    expect(htmlToText('<p>Оценка &lt; 5, а порог &gt; 3</p>')).toBe('Оценка < 5, а порог > 3')
  })

  it('оставляет содержимое script текстом, а сам тег вырезает', () => {
    expect(htmlToText('<script>alert(1)</script>')).toBe('alert(1)')
  })

  it('не оставляет обрывков от незакрытого тега', () => {
    expect(htmlToText('<p>текст<b>')).toBe('текст')
  })
})

describe('признак разметки', () => {
  it('узнаёт разметку', () => {
    expect(looksLikeHtml('<p class="x">текст</p>')).toBe(true)
    expect(looksLikeHtml('текст<br>ещё')).toBe(true)
  })

  it('не принимает за разметку обычные угловые скобки', () => {
    // Иначе в отчёте о переносе всплывёт предупреждение там, где чистить нечего.
    expect(looksLikeHtml('оценка < 5 и > 3')).toBe(false)
    expect(looksLikeHtml('просто текст')).toBe(false)
  })
})
