/**
 * Which OAuth scopes the app needs, and how to recognise the portal refusing for lack of them.
 *
 * Список собран не из памяти, а из документации: у каждого метода в `b24-dev-mcp` есть поле
 * `Scope`, и оно сверено поимённо. Правило проекта требует именно этого — «права доступа
 * берутся из документации, а не из памяти».
 *
 * ⚠ Ловушка, ради которой файл и заведён: `userfieldconfig.add` живёт в модуле `crm`,
 * страница его документации лежит в разделе CRM, а scope у него СВОЙ — `userfieldconfig`.
 * Выдать приложению один `crm` — самая естественная ошибка при регистрации в кабинете,
 * и цена у неё несимметричная: `crm.type.add` пройдёт и создаст смарт-процесс, а следующий
 * же `userfieldconfig.add` упадёт. На портале останется смарт-процесс без полей — при лимите
 * 150 на весь портал на Базовом тарифе, и этот лимит не наш.
 *
 * ⚠ ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ И ПОЧЕМУ. Первая редакция (PR #30) сверяла этот список
 * с `portal.scope` ДО первого вызова: не начинать дешевле, чем остановиться посередине.
 * Живой портал показал, что посылка неверна. На `b24-ypkv9c.bitrix24.by` сохранённый
 * `scopes` равен `{app}` — при том что установка прошла целиком и `crm.type.add`,
 * `userfieldconfig.add` и `placement.bind` на нём отработали. То есть `scope` в ответе
 * сервера авторизации при обмене по `refresh_token` НЕ перечисляет выданные права, и
 * проверка запрещала бы установку порталу, на котором всё работает. Правило проекта:
 * приоритет у наблюдения, и расхождение записано в `docs/PROCESS.md`.
 *
 * Поэтому правду о правах спрашиваем у портала, а не предсказываем: недостающий scope
 * он называет сам, кодом `insufficient_scope`.
 */

/**
 * Разрешения, которые нужно отметить в партнёрском кабинете.
 *
 * | Разрешение | Что им вызываем |
 * |---|---|
 * | `crm` | `crm.type.add`, `crm.type.list`, `crm.item.*`, `crm.deal.get`, `crm.timeline.comment.add` |
 * | `userfieldconfig` | `userfieldconfig.add`, `userfieldconfig.list` — поля смарт-процессов |
 * | `placement` | `placement.bind`, `placement.unbind` — вкладка в карточке сделки |
 *
 * Базовые и потому не отмечаемые: `user.admin`, `app.option.get`, `app.option.set`,
 * `profile`, `app.info`. `bizproc` появится вместе с роботами, которых пока нет.
 *
 * Список не проверяется автоматически — он попадает в журнал рядом с отказом портала,
 * чтобы администратору не пришлось искать его в документации в момент разбора.
 */
export const REQUIRED_SCOPES = ['crm', 'userfieldconfig', 'placement'] as const

/**
 * Отказал ли портал именно из-за нехватки прав приложения.
 *
 * ⚠ Отличать это от прочих отказов обязательно: нехватка прав лечится галочкой
 * в партнёрском кабинете, а не повтором через минуту. Показать администратору
 * «попробуйте позже» на неисправимую сам собой причину значит отправить его жать кнопку
 * столько раз, сколько у него терпения.
 *
 * Ищем код, а не текст: `insufficient_scope` — машинный код сервера Битрикс24, он
 * не переводится и не меняется от локали портала. Сравнение регистронезависимое,
 * потому что в сообщение об ошибке код попадает по-разному в зависимости от того,
 * SDK его пересказал или мы прочитали ответ сами.
 */
export function looksLikeScopeRefusal(reason: string): boolean {
  return reason.toLowerCase().includes('insufficient_scope')
}
