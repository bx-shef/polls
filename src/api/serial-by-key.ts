/**
 * Последовательное выполнение по ключу: пока работа с ключом K не закончилась, вторая работа с тем же
 * K ждёт. Разные ключи не мешают друг другу.
 *
 * **Зачем это здесь.** Признак «по этому переходу уже приглашали» — дело в таймлайне сделки на стороне
 * портала (`docs/process.md`, шаг 5). Проверяется оно двумя операциями: найти своё дело по маркеру →
 * если нет, создать. Между ними есть промежуток, и он не теоретический: событие изменения сделки
 * приходит на КАЖДУЮ правку, а правки идут гроздью вокруг перехода, то есть два обработчика реально
 * бывают в воздухе одновременно. Оба сходили бы за списком дел, оба увидели бы пустоту, оба создали бы
 * своё — и маркер бы не помог: он гарантирует, что ключ не совпадёт СЛУЧАЙНО, но не мешает нам самим
 * записать под ним дважды.
 *
 * ⚠️ **И закрывается это в нашем коде, без всякого хранилища.** Никто, кроме нас, таких дел не
 * создаёт — значит и очередь на ключ нужна только внутри нашего процесса. Здесь нет ни записи в базу,
 * ни отметки «уже сделано»: есть ровно одно свойство — две работы с одним ключом не идут внахлёст.
 * Ничего не сохраняется: как только очередь по ключу опустела, ключ забывается.
 *
 * ⚠️ Граница честно: сериализация **внутрипроцессная**. Пока инстанс один (а он один — см. карту
 * проекта, §Развёртывание), этого достаточно. При нескольких репликах два процесса снова смогут
 * оказаться в промежутке одновременно, и тогда понадобится общая на все реплики блокировка —
 * это часть работы по мультитенанту/scale-out, а не сегодняшняя.
 */
export interface KeySerializer {
  /** Выполнить `fn` так, чтобы работы с одинаковым `key` не пересекались во времени. */
  run<T>(key: string, fn: () => Promise<T>): Promise<T>
  /** Сколько ключей сейчас занято. Только для тестов: гарантия «карта не растёт» иначе непроверяема. */
  size(): number
}

export function createKeySerializer(): KeySerializer {
  // Хвост очереди по ключу. Промис здесь НИКОГДА не отвергается (см. `settled` ниже) — иначе отказ
  // одной работы рвал бы очередь и следующая с тем же ключом не запустилась бы вовсе.
  const tails = new Map<string, Promise<void>>()

  return {
    run<T>(key: string, fn: () => Promise<T>): Promise<T> {
      const prev = tails.get(key) ?? Promise.resolve()
      // Вызывающему возвращаем НАСТОЯЩИЙ результат — со всеми отказами: проглотить чужую ошибку
      // ради собственного удобства значило бы превратить сбой в тишину.
      const result = prev.then(fn)
      const settled = result.then(() => undefined, () => undefined)
      tails.set(key, settled)
      // Ключ живёт ровно пока по нему есть работа. Сверка `tails.get(key) === settled` обязательна:
      // если за это время встала следующая работа, хвост уже её, и удалять его нельзя.
      void settled.then(() => {
        if (tails.get(key) === settled) tails.delete(key)
      })
      return result
    },
    size: () => tails.size
  }
}
