import { SlidingWindowLimiter } from '~core/api/ratelimit'

/**
 * Лимит запросов дашборда (#49). ДВА потолка на разных ключах и на разных стадиях запроса — потому
 * что защищают они разное.
 *
 * ⚠️ Повод не «оптимизация». `/api/dashboard/:key` читает в память ВСЕ ответы опроса и считает по
 * ним восемь агрегатов синхронно. С мультитенантом один сотрудник одного портала, зажавший F5 на
 * большом опросе, выедает пул соединений и event loop **всем арендаторам** сразу — то есть чужие
 * порталы получают отказ из-за чужой активности. До SQL-агрегации (тот же #49) потолок это
 * единственное, что стоит между одним человеком и всеми остальными.
 *
 * **Пер-IP, ДО авторизации.** Гейт сессии дешёвый (HMAC), но `resolveSessionPortal` уже ходит в базу,
 * а страница отдаётся по адресу, открытому из интернета. Этот потолок бьёт по флуду БЕЗ сессии и
 * стоит первым, до всякой работы.
 *
 * **Пер-портал, ПОСЛЕ подтверждения тенанта.** Ключ — числовой `portal.id` из подписанной сессии,
 * то есть подделать его нельзя, а за корпоративным прокси все сотрудники приходят с одного адреса
 * (урок пер-IP потолка handshake: там низкий порог на общий адрес давал 429 одиннадцатому открытию
 * виджета). Именно этот потолок и делает шум одного арендатора его собственной проблемой.
 *
 * ⚠️ Глобальный потолок ставится ЯВНО и считается тем же лимитером, что и пер-портальный, под
 * отдельным ключом: сумма пер-портальных потолков растёт с числом установленных порталов, а пул
 * соединений — нет.
 *
 * In-memory, на инстанс (общий стор — #4): рестарт сбрасывает окно ≤60 секунд, это fail-open на одно
 * окно, и цена его здесь ниже, чем round-trip в ту самую базу, которую потолок защищает.
 */
export interface DashboardLimiterOptions {
  /** Потолок на адрес за окно — до авторизации. */
  ipLimit?: number
  /** Потолок на портал за окно — после подтверждения тенанта. */
  portalLimit?: number
  /** Суммарный потолок инстанса за окно. */
  globalLimit?: number
  windowMs?: number
}

export interface DashboardLimiter {
  /** true — запрос допущен (и учтён) потолком адреса. Зовётся ПЕРВЫМ, до всякой работы. */
  allowIp(ip: string, now?: Date): boolean
  /** true — запрос допущен (и учтён) потолками портала и инстанса. Зовётся ПОСЛЕ резолва тенанта. */
  allowPortal(portalId: number | undefined, now?: Date): boolean
}

/** Ключ портала в режиме памяти/dev: `portalId` там `undefined`, но потолок нужен и в нём. */
const MEMORY_PORTAL_KEY = 'memory'
const GLOBAL_KEY = 'all'

/**
 * Фабрика — чтобы тест мог собрать свой экземпляр с крошечными потолками и своими часами. Боевой
 * экземпляр ниже; модульное состояние на процесс, как у остальных лимитеров.
 */
export function createDashboardLimiter(opts: DashboardLimiterOptions = {}): DashboardLimiter {
  const windowMs = opts.windowMs ?? 60_000
  const ip = new SlidingWindowLimiter({ limit: opts.ipLimit ?? 60, windowMs })
  const portal = new SlidingWindowLimiter({ limit: opts.portalLimit ?? 60, windowMs })
  const global = new SlidingWindowLimiter({ limit: opts.globalLimit ?? 600, windowMs })
  return {
    allowIp: (key, now = new Date()) => ip.allow(key, now),
    // ⚠️ Порядок операндов значения не имеет, а вот `&&` — имеет: короткое замыкание НЕ учитывает
    // второй потолок, когда первый уже отказал. Это намеренно — отказанный запрос работы не делает,
    // и учитывать его дважды значит наказывать арендатора за отказ соседа.
    allowPortal: (portalId, now = new Date()) =>
      portal.allow(portalId === undefined ? MEMORY_PORTAL_KEY : String(portalId), now) &&
      global.allow(GLOBAL_KEY, now)
  }
}

/** Боевой экземпляр роута дашборда. */
export const dashboardLimiter = createDashboardLimiter()

