/**
 * Справка сервиса — ЕДИНЫЙ реестр (#209-подход соседнего проекта: документация живёт одним источником).
 *
 * Из этого файла читают ТРИ потребителя, и это несущее решение, а не удобство:
 *  1. слайдер подсказок в интерфейсе (`HelpSlider.vue`) — пояснение «по месту», не уводя из экрана;
 *  2. публичная страница `/docs` — та же справка целиком, для чтения до установки;
 *  3. `/llms.txt` + `/llms-full.txt` — та же справка для ИИ-ассистентов (паттерн b24ui:
 *     индекс со ссылками + полный текст одним файлом).
 * Второй копии текста нет — она не могла бы не устареть. Внутренние документы (`docs/*.md`) сюда НЕ
 * попадают: они про устройство и решения, а эта справка — про то, как сервисом пользоваться.
 *
 * ⚠️ Формат — СТРУКТУРА, а не markdown. В `app/**` запрещён `v-html` (гард с пустым белым списком в
 * `test/tenant-routes.test.ts`), и мини-рендер разметки означал бы либо нарушение запрета, либо
 * второй парсер. Секции из абзацев и списков рендерятся честными `{{ }}` — и их же тривиально
 * собрать в markdown для llms.txt.
 *
 * ⚠️ Слой — `~core/client` намеренно: данные без секретов нужны и клиентским экранам (слайдер,
 * `/docs`), и Nitro-роутам (`llms.txt`). Это единственный слой, который видят оба.
 */

export interface HelpSection {
  /** Подзаголовок секции; первая секция обычно без него. */
  heading?: string
  /** Абзацы обычного текста. */
  paragraphs?: string[]
  /** Маркированный список после абзацев. */
  bullets?: string[]
}

export interface HelpTopic {
  /** Стабильный ключ: по нему тема открывается из интерфейса и адресуется в llms.txt. */
  key: string
  /** Заголовок темы. */
  title: string
  /** Одно предложение для индекса `/llms.txt` и карточек `/docs`. */
  summary: string
  sections: HelpSection[]
}

