/**
 * Names of everything the app puts into a client portal, exactly as the portal shows them.
 *
 * ⚠ ОДИН ИСТОЧНИК НА ОБЕ СТОРОНЫ. По этим строкам сервер создаёт и переименовывает смарт-процессы
 * и вкладки, а страницы приложения ссылаются на них словами: «откройте вкладку … в карточке
 * сделки». Пока названия вписывались в тексты страниц руками, тексты разошлись с порталом
 * за один PR — справка и пустые состояния вели на вкладки, которых на портале уже не было.
 * Поэтому здесь, в `shared/`: `app/` импортировать `server/` не может (граница проверяется
 * скриптом), а `shared/` доступен обоим. Нашли `/review` и `/code-review` в PR #87.
 *
 * ⚠ Метка владельца `[sh]` — решение владельца 28.09 (issue #84, пункт 22): смарт-процессы,
 * подписи наших полей и вкладки носят этот префикс. Зачем, по пунктам:
 * - в списках смарт-процессов, полей и вкладок клиента наше отличается от его собственного
 *   с первого взгляда — полей в карточке сделки у клиента десятки;
 * - это метка владельца, а не бренд приложения: её видит администратор и сотрудники портала,
 *   а респондент на публичной странице анкеты не видит нигде.
 *
 * ⚠ Защитой от чужого одноимённого смарт-процесса метка НЕ служит. По названию мы находим
 * смарт-процесс, если потеряли его идентификатор (`findTypeByTitle`), и ищем при этом и прежние
 * голые названия — иначе портал, обустроенный до метки, получил бы дубликат. Значит, чужой
 * «Шаблон опроса» клиента по-прежнему может быть взят за наш; поэтому переименовываем и
 * перенастраиваем только смарт-процессы, известные по сохранённому идентификатору (разбор —
 * у `ensureOwnership` в `server/b24/provision.ts`). Прежний текст здесь обещал, что с меткой
 * шанс «усыновить» чужой падает почти до нуля, — это было неправдой, пока ищутся голые названия.
 *
 * Коды полей (`UF_CRM_…`) метки не получают: портал их не переименовывает, а новые поля
 * со старыми данными не связаны.
 */
export const OWNER_PREFIX = '[sh]'

/** Prefixes a portal-facing name with the owner mark: `[sh] Код шаблона`. */
export function ownerLabel(text: string): string {
  return `${OWNER_PREFIX} ${text}`
}

