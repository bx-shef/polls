import { defineEventHandler, getRequestHeader, setResponseHeader, setResponseStatus, type H3Event } from 'h3'
import { bodyLimitStatus, CONTENT_LENGTH_HEADER, TRANSFER_ENCODING_HEADER } from '~core/api/body-limit'

/**
 * Общий потолок размера тела — ДО маршрутизации, на каждый запрос.
 *
 * Почему middleware, а не проверка в роутах (она там тоже есть, и остаётся). Поимённые капы защищают
 * ровно те роуты, где автор о них вспомнил; забытый роут выглядит точно так же, как защищённый, и
 * тишина в логах ничем не отличается. Здесь проверка стоит перед маршрутизацией, поэтому новый роут
 * получает её сам, ничего для этого не делая, — а публичные вебхуки Bitrix24, которые буферизовали
 * тело `readBody` **до** сверки токена, перестают быть каналом OOM.
 *
 * ⚠️ Middleware не видит статику (обработчик публичных файлов Nitro регистрируется раньше — это
 * подробно разобрано в `server/plugins/security-headers.ts`). Здесь это неважно: статика отвечает
 * только на GET/HEAD, а у них тела нет.
 *
 * ⚠️ **Форма отказа отличается от штатной у части роутов.** Вебхуки Bitrix24 отдают текстовое `ok`,
 * страница завершения установки — HTML; отсюда уедет `{ ok: false, error }`. Это осознанно: разбирать
 * ожидаемый формат ответа до маршрутизации значило бы повторить здесь таблицу роутов.
 *
 * ⚠️ **Осознанное сужение инварианта «всегда 200»** у `/api/b24/deal-update` и `/api/b24/robot`
 * (у `/api/b24/install` инвариант и раньше был не абсолютным — там есть 400/429/502/503). Инвариант
 * существует, чтобы не раскрывать анонимному вызывающему, установлен ли портал и верен ли токен. Отказ
 * здесь принимается по одному заголовку, до единого обращения к хранилищу, поэтому оракулом не служит:
 * он одинаков для настоящего портала и для случайного сканера (проверено — статус, тело, заголовки и
 * время ответа совпадают с ответом на несуществующий маршрут). Сохранить 200 без чтения тела всё равно
 * невозможно — а прочитать его и значит согласиться на то, от чего защищаемся. Легальному трафику это
 * недостижимо: события приходят form-urlencoded с `Content-Length` в единицы килобайт.
 *
 * Импорты из `h3` **явные**, а не через авто-импорты Nitro, — иначе файл нельзя загрузить в vitest, и
 * единственным «тестом» остаётся греп по исходнику. Он и был: мутация `if (!verdict) return` →
 * `if (verdict) return` полностью выключала бэкстоп, а тесты оставались зелёными.
 */

/**
 * Решение по одному запросу. Вынесено из `defineEventHandler` **ради исполняемого теста**: возврат
 * значения из middleware завершает запрос (h3 пишет тело и выходит из цепочки слоёв), `undefined` —
 * пропускает дальше, и оба пути проверяются напрямую.
 */
export function handleBodyLimit(event: H3Event): { ok: false, error: string } | undefined {
  const verdict = bodyLimitStatus({
    // ⚠️ Дубли `Content-Length` сюда не доходят: их отвергает сам HTTP-парсер Node
    // (`HPE_UNEXPECTED_CONTENT_LENGTH`, даже при одинаковых значениях), как и пару
    // `Content-Length` + `Transfer-Encoding` (`HPE_INVALID_TRANSFER_ENCODING`) — проверено. Строгий
    // разбор в ядре — вторая линия: он не зависит от того, чей парсер стоит перед нами.
    contentLength: getRequestHeader(event, CONTENT_LENGTH_HEADER),
    transferEncoding: getRequestHeader(event, TRANSFER_ENCODING_HEADER)
  })
  if (!verdict) return undefined

  setResponseStatus(event, verdict.status)
  // ⚠️ Без этого отказ НЕ прекращает заливку. Node после `res.end()` вычитывает остаток тела в никуда
  // (`req._dump()`), чтобы соединение осталось пригодным для следующего запроса, — и отправитель,
  // который игнорирует ранний ответ (а настоящий атакующий именно такой; `curl` так себя не ведёт),
  // спокойно дольёт заявленные сотни мегабайт. Память при этом цела, тело нигде не копится, но канал
  // и процессорное время сжигаются, то есть отказ в обслуживании остаётся — просто дешевле.
  // Измерено на собранном приложении: без заголовка сервер принял все 300 МБ.
  setResponseHeader(event, 'connection', 'close')
  return { ok: false, error: verdict.error }
}

export default defineEventHandler(handleBodyLimit)
