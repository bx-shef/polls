/**
 * Decides whether an in-portal page may show its interface.
 *
 * Страницы приложения осмысленны ТОЛЬКО внутри Битрикс24: снаружи у них нет фреймового
 * токена, значит нет ни портала, ни прав, ни единого вызова REST. Интерфейс при этом
 * выглядит рабочим — кнопки на месте, — и человек считает, что приложение сломано,
 * хотя оно просто открыто не оттуда.
 *
 * ⚠ Сейчас гейт применён к ОДНОЙ странице — `/app`. У `/install` и у вкладки сделки своя,
 * более ранняя обработка «фрейма нет», и они на этот гейт ещё не переведены. Первая редакция
 * этого комментария писала «`/app`, `/install` и вкладка сделки», то есть обещала общий приём
 * там, где его нет: читатель решил бы, что все три уже защищены одинаково. Перевод остальных —
 * отдельный шаг, issue заведён. Нашла панель ревью PR #28.
 *
 * ⚠ Приём и его обоснование взяты у соседнего проекта (`client-bank-alfa-by`,
 * `app/utils/inPortalGate.ts`), где это оплачено живыми порталами. Там же сформулировано
 * главное: здесь легко ошибиться В ПОЛЬЗУ «показать», а «показать» на этом гейте — это
 * пустая панель, которую пользователь читает как поломку.
 *
 * Логика вынесена из компонента, потому что проверяется вызовом, а не смонтированным фреймом.
 */

export type PortalGate = 'checking' | 'ok' | 'outside'

export interface PortalGateInput {
  /** Проверка присутствия во фрейме завершилась: `initializeB24Frame()` асинхронный. */
  resolved: boolean
  /** Мы внутри портала. */
  inPortal: boolean
  /** Явный обход для разработки и скриншотов: `?preview=1`. */
  preview: boolean
}

/**
 * Что рендерить.
 *
 * ⚠ Состояние `checking` обязательно. Без него интерфейс мелькает и схлопывается в заглушку
 * (или наоборот), а мелькание читается как поломка вернее, чем честное ожидание.
 *
 * `preview` перекрывает всё намеренно: на нём держатся тесты, монтирующие страницы вне фрейма.
 */
export function portalGate(input: PortalGateInput): PortalGate {
  if (input.preview) return 'ok'
  if (!input.resolved) return 'checking'
  return input.inPortal ? 'ok' : 'outside'
}

/**
 * Считать ли `?preview` обходом.
 *
 * ⚠ Только явная единица. Голый `?preview` без значения обходом НЕ считается: случайная
 * ссылка не должна открывать интерфейс, который снаружи портала не работает.
 *
 * Массив — это `?preview=1&preview=0`; засчитываем, если хотя бы одно значение равно `1`.
 */
export function isPreview(value: unknown): boolean {
  if (Array.isArray(value)) return value.some(isPreview)
  return value === '1'
}
