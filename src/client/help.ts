/** Тема по ключу — для слайдера и роутов. `undefined` — ключа нет (опечатка ловится тестом). */
export function helpTopic(key: string): HelpTopic | undefined {
  return HELP_TOPICS.find((t) => t.key === key)
}

/** Название сервиса в шапках llms-файлов. Единственная копия. */
export const HELP_PRODUCT = 'Опросы для Bitrix24'
const HELP_PRODUCT_SUMMARY =
  'Сервис опросов внутри Bitrix24: приглашение из сделки, ответ клиента по одноразовой ссылке, результат в карточку сделки, аналитика по срезам.'

/** Тема → markdown (для `/llms-full.txt`; экранировать нечего — текст и печатается текстом). */
export function topicMarkdown(t: HelpTopic): string {
  const out: string[] = [`## ${t.title}`, '']
  for (const s of t.sections) {
    if (s.heading) out.push(`### ${s.heading}`, '')
    for (const p of s.paragraphs ?? []) out.push(p, '')
    for (const b of s.bullets ?? []) out.push(`- ${b}`)
    if (s.bullets?.length) out.push('')
  }
  return out.join('\n')
}

/**
 * `/llms.txt` — индекс по конвенции llms.txt (как у b24ui): имя, описание, ссылки с аннотациями.
 * `baseUrl` пустой — ссылки относительные (dev без домена).
 */
export function buildLlmsTxt(baseUrl: string): string {
  const base = baseUrl.replace(/\/$/, '')
  const lines = [
    `# ${HELP_PRODUCT}`,
    '',
    `> ${HELP_PRODUCT_SUMMARY}`,
    '',
    '## Документация',
    '',
    `- [Вся справка одним файлом](${base}/llms-full.txt)`,
    ...HELP_TOPICS.map((t) => `- [${t.title}](${base}/docs#${t.key}): ${t.summary}`)
  ]
  return lines.join('\n') + '\n'
}

/** `/llms-full.txt` — вся справка одним markdown-файлом. */
export function buildLlmsFullTxt(): string {
  return [`# ${HELP_PRODUCT}`, '', `> ${HELP_PRODUCT_SUMMARY}`, '', ...HELP_TOPICS.map(topicMarkdown)].join('\n')
}
