import { drainInbox, purgeExpiredAnswers, requeueStuck } from '../answers/deliver'
import { isDatabaseConfigured } from '../db/client'
import { forgetExpiredLinkHeaders } from '../links/forget'
import { healDegradedPortals, requeueStuckProvisioning } from '../portals/heal'
import { purgeDeadPortals } from '../portals/store'
import { deliveryDisabled, deliveryIntervalSeconds } from '../utils/env'
import { logger } from '../utils/logger'

/** Как часто убирать персональные данные с истёкшим сроком. Час, а не тик: см. разбор ниже. */
const PURGE_EVERY_MS = 60 * 60 * 1000

/**
 * Когда убирали в прошлый раз.
 *
 * ⚠ Ноль, а не `Date.now()`: первый заход после подъёма обязан состояться сразу. Иначе
 * приложение, которое перезапускают чаще раза в час (деплой, перезапуск контейнера),
 * не убрало бы НИКОГДА — механизм выглядел бы рабочим и не работал.
 */
let lastPurgeAt = 0

/**
 * Runs the answer-delivery loop inside the app process.
 *
 * Отдельного воркера пока нет намеренно. Объём работы — единицы ответов в день на портал,
 * и второй контейнер ради этого означал бы второй образ, второй деплой и второе место,
 * где кончаются токены. `FOR UPDATE SKIP LOCKED` делает цикл безопасным при нескольких
 * экземплярах приложения, поэтому вынести его в отдельный процесс можно будет позже,
 * не переписывая: достаточно поднять тот же образ с `ANSWER_DELIVERY=off` у веб-части.
 *
 * ⚠ Цикл не ждёт своего срабатывания после приёма ответа: страница дёргает разбор сразу,
 * и в норме ответ уезжает в портал за секунды. Интервал здесь — страховка на случай,
 * когда портал был недоступен и попытку отложили.
 */
export default defineNitroPlugin(() => {
  if (deliveryDisabled()) {
    logger.info({}, 'доставка ответов выключена в этом процессе (ANSWER_DELIVERY=off)')
    return
  }
  if (!isDatabaseConfigured()) {
    // Без базы буфера нет вовсе. Молчать нельзя: снаружи это выглядит как «ответы копятся».
    logger.warn({}, 'доставка ответов не запущена: база не настроена')
    return
  }

  const intervalMs = deliveryIntervalSeconds() * 1000
  let running = false

  const tick = async () => {
    // Захода на заход не наслаиваем: медленный портал иначе накопил бы столько параллельных
    // разборов, сколько прошло тиков, и добил бы себя же.
    if (running) return
    running = true
    try {
      await requeueStuck()
      const result = await drainInbox()
      if (result.delivered > 0 || result.failed > 0) logger.info(result, 'разбор буфера ответов')

      // ⚠ Уборщик мёртвых порталов висит на ЭТОМ тике, а не на своём таймере. Своего
      // не завели намеренно: второй таймер — это второе место, где цикл может не запуститься,
      // и второй же набор гвардов на «а он вообще тикает». Работы у уборщика на пустом
      // множестве ровно один индексный запрос раз в минуту.
      //
      // Порог — месяц молчания портала, см. `server/domain/portals/lifecycle.ts`.
      //
      // ⚠ Свой `try`: уборщик от разбора буфера не зависит ничем, а в общем блоке упавший
      // разбор глушил бы его бессрочно — и молча, потому что в журнал уходила бы строка
      // про буфер ответов. Нашла повторная панель ревью PR #34.
      try {
        const purged = await purgeDeadPortals(new Date())
        if (purged > 0) logger.warn({ purged }, 'стёрты порталы с мёртвым грантом')
      }
      catch (error) {
        // Причину записать МОЖНО: здесь только ошибки Postgres, ответов клиентов на этом
        // пути нет вовсе — в отличие от разбора буфера ниже.
        logger.error({ reason: (error as Error).message }, 'уборка мёртвых порталов сорвалась')
      }

      // ⚠ Второй уборщик — истёкших ответов, и он ОТДЕЛЬНЫМ `try` по той же причине, что
      // первый: упавшая уборка порталов не должна глушить уборку ответов, иначе
      // единственный предельный срок хранения персональных данных отключился бы молча
      // из-за беды в соседнем механизме. Срок и разбор — `purgeExpiredAnswers`.
      //
      // ⚠ НЕ ЧАЩЕ РАЗА В ЧАС, и это предохранитель, а не экономия. Потолок за заход
      // не ограничивает ущерб, пока частота задаётся `ANSWER_DELIVERY_INTERVAL`: он
      // принимает пять секунд, то есть двенадцать заходов в минуту и 864 тысячи строк
      // в сутки вместо обещанных «пятидесяти в минуту». Ровно та ловушка, на которой
      // обжёгся сосед и о которой предупреждает `purgeDeadPortals`. Срок хранения меряется
      // сутками — минутная точность ему не нужна. Нашёл `/code-review` в PR #53.
      // ⚠ ЗАМОК ВРЕМЕНИ ОДИН НА ДВА УБОРЩИКА, А `try` У КАЖДОГО СВОЙ. Замок общий, потому
      // что причина у него одна — частота тика задаётся снаружи (`ANSWER_DELIVERY_INTERVAL`
      // принимает пять секунд), и потолок за заход без часового замка ущерб не ограничивает.
      // `try` раздельные, потому что это два независимых предельных срока хранения: упавшая
      // уборка буфера не должна глушить забывание имён, и наоборот.
      //
      // ⚠ Отметка ставится ДО обоих, а не внутри первого. Внутри — и второй уборщик увидел бы
      // замок уже взведённым, то есть не запустился бы никогда, а выглядел бы рабочим.
      const purgeDue = Date.now() - lastPurgeAt >= PURGE_EVERY_MS
      if (purgeDue) lastPurgeAt = Date.now()

      if (purgeDue) {
        try {
          const forgotten = await purgeExpiredAnswers(new Date())
          if (forgotten > 0) logger.warn({ forgotten }, 'истёкшие ответы стёрты из буфера')
        }
        catch (error) {
          // ⚠ Причину записать можно и здесь: `purgeExpiredAnswers` ходит только в Postgres
          // и в портал не заглядывает, то есть процитированного ответа клиента в её ошибке
          // взяться неоткуда. Это ровно та развилка, из-за которой ниже причина НЕ пишется.
          logger.error({ reason: (error as Error).message }, 'уборка истёкших ответов сорвалась')
        }

        // ⚠ Третий уборщик, заведён инвентаризацией базы 25.09: шапка приглашения — имена
        // людей, и у истёкшей ссылки она держалась вечно, хотя и схема, и `revokeLink`
        // утверждали обратное. Разбор — в `forgetExpiredLinkHeaders`.
        try {
          const forgotten = await forgetExpiredLinkHeaders(new Date())
          if (forgotten > 0) logger.info({ forgotten }, 'шапки истёкших приглашений забыты')
        }
        catch (error) {
          // Тоже только Postgres: ни портала, ни ответа клиента на этом пути нет.
          logger.error({ reason: (error as Error).message }, 'забывание шапок сорвалось')
        }

        // ⚠ Четвёртый — долечивание порталов, застрявших в `degraded` (issue #12). Он
        // единственный здесь ХОДИТ В ПОРТАЛ: обустройство это 17–19 вызовов под бюджетом
        // в 45 секунд, и час — та пауза, при которой это не мешает никому.
        //
        // ⚠ Возврат брошенных и само лечение — в ОДНОМ `try`, в отличие от соседей выше.
        // Они независимы, а эти двое нет: возврат готовит работу, которую лечение забирает.
        // Разнеся их, мы получили бы лечение, которому нечего брать, и молчание вместо
        // объяснения.
        try {
          await requeueStuckProvisioning(new Date())
          const healed = await healDegradedPortals(new Date())
          if (healed > 0) logger.warn({ healed }, 'порталы долечены: обустройство прошло со второго раза')
        }
        catch (error) {
          // ⚠ Причину записать можно: ответов клиентов на этом пути нет вовсе. А вот отказы
          // самого портала сюда не доходят — обустройство разбирает их исходом, не броском.
          logger.error({ reason: (error as Error).message }, 'долечивание порталов сорвалось')
        }
      }
    }
    catch {
      // Упавший тик не должен уносить цикл: следующий разберётся.
      //
      // ⚠ Причина не записывается, и это не лень. Ниже по стеку лежат вызовы портала,
      // в параметрах которых едет ответ клиента, а Битрикс24 любит цитировать присланное
      // значение в тексте ошибки валидации. Свои отказы разбор записывает сам и безопасно
      // (`server/domain/answers/portal-errors.ts`); сюда доходит только то, что он не поймал.
      logger.error({}, 'разбор буфера ответов сорвался')
    }
    finally {
      running = false
    }
  }

  const timer = setInterval(() => void tick(), intervalMs)
  // `unref` — чтобы таймер не держал процесс живым при остановке контейнера.
  timer.unref?.()

  logger.info({ intervalSeconds: deliveryIntervalSeconds() }, 'доставка ответов запущена')
})
