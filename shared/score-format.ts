/**
 * A score written the Russian way: a comma, not a point, and no trailing zeros.
 *
 * ⚠ ОДНА запись на все места, где человек видит балл: дело в ленте сделки, поле «Результат опроса»
 * и строка списка во вкладке сделки. Одно прохождение не должно называться «7.5» в одном месте
 * и «7,5» в другом. Живёт в `shared/`, потому что нужна обеим сторонам, а `app/` импортировать
 * `server/` не может: прежде вкладка держала побуквенную копию, и первая же правка формата
 * (скажем, округление) развела бы их молча. Нашли `/review` и `/code-review` в PR #89.
 */
export function formatScore(score: number): string {
  return String(score).replace('.', ',')
}
