/**
 * When a portal stops being ours, and when we may erase it.
 *
 * ⚠ Существует потому, что штатного способа узнать об удалении приложения у нас НЕТ,
 * и это не упущение, а свойство тиражного приложения с пунктом в левом меню. Проверено
 * на живом портале 18.09.2026: после `installFinish()` событие `ONAPPINSTALL` не приходит,
 * а `application_token` приходит ТОЛЬКО в событиях. Для `ONAPPUNINSTALL` сравнение этого
 * токена — единственный способ проверки в принципе: данных авторизации в событие удаления
 * не передают, приложение уже удалено. Без токена обработчик принимал бы «сотрите портал X»
 * от кого угодно из интернета, то есть был бы кнопкой отключения чужого клиента.
 *
 * Значит об уходе клиента мы узнаём не из события, а из ВЫВОДА: сервер авторизации перестал
 * обменивать наш грант. Это надёжнее события — его не подделать снаружи, потому что это наш
 * собственный исходящий вызов, — но медленнее, и потому здесь есть отсрочка.
 *
 * Приём взят у `client-bank-alfa-by` (`grant_revoked_at`, уборщик #574).
 */
import { refusalCode } from './portal-error'

/**
 * Коды, после которых грант считается мёртвым.
 *
 * Взяты из документации сервера авторизации (`oauth.bitrix24.tech`, «Коды ошибок сервера
 * авторизации»), а не из памяти — правило проекта. Там ровно пять кодов, и мёртвый грант
 * означают два:
 *
 * | Код | Что значит по документации |
 * |---|---|
 * | `invalid_grant` | «Переданы некорректные авторизационные данные… Если истёк `refresh_token`, пройдите авторизацию заново» |
 *
 * ⚠ `invalid_client` стоял здесь и УБРАН. Документация говорит про него «Переданы некорректные
 * данные клиента… **Проверьте `client_id` и `client_secret`**» — то есть про НАШУ пару, одну
 * на весь флот, а не про грант конкретного портала. Незаконченная ротация секрета пометила бы
 * мёртвыми все порталы разом, а предохранитель по доле на сегодняшнем флоте из одного портала
 * выключен. Приписка «возможно, приложение не установлено» из той же строки документации —
 * не повод: под то же описание подходит и наша собственная опечатка. Сосед
 * (`client-bank-alfa-by`) держит в списке смерти только `invalid_grant`, и это измерено
 * им на живом сервере авторизации, а не выведено. Нашли трое на повторной панели PR #34.
 *
 * ⚠ Чего здесь НЕТ и почему — каждый пункт оплачен разбором на панели ревью PR #34:
 *
 * - **`PAYMENT_REQUIRED`** — «истёк пробный или оплаченный период». Клиент никуда не делся,
 *   он просто не продлил оплату. Стереть ему токены значит наказать за просрочку платежа
 *   потерей установки.
 * - **`insufficient_scope` / `invalid_scope`** — не хватает прав в карточке приложения.
 *   Наша ошибка регистрации, а не уход клиента.
 * - **`invalid_request`** — «некорректно сформированный запрос». Наш баг, и он пометил бы
 *   все порталы разом.
 * - **`NO_AUTH_FOUND`** — «в запросе нет авторизационных данных вовсе». Тоже наш баг:
 *   разъехавшийся ключ шифрования или сборка параметров. Стоял в первой редакции, убран.
 * - **`expired_token`** — истёк `access_token`, и SDK продлевает его сам. Дойдя до нас,
 *   он означает, что продление БЫЛО, то есть грант жив. Стоял в первой редакции, убран.
 * - **`PORTAL_DELETED`** — в документации привязан к закрытию публичной части сайта
 *   у коробочной установки, а не к удалению приложения. Стоял в первой редакции, убран.
 * - **`INVALID_CREDENTIALS`** — по документации это «не найден активный вебхук с указанным
 *   идентификатором пользователя и секретным кодом», то есть про локальные вебхуки. Наш путь
 *   авторизации — OAuth, и к нему код отношения не имеет вовсе. (Первая редакция объясняла его
 *   как «наша пара `client_id`/`client_secret`» — это была догадка, документация говорит другое.)
 *
 * Общее правило, по которому собран список: сюда попадает только то, что НЕ МОЖЕТ быть
 * вызвано нашей собственной ошибкой. Иначе одна опечатка в конфигурации помечает весь флот,
 * и через месяц уборщик стирает всех клиентов сразу.
 */
const DEAD_GRANT_CODES: readonly string[] = ['invalid_grant']

/**
 * Мёртв ли грант портала.
 *
 * ⚠ Принимает ОШИБКУ, а не строку, и читает структурный код через `refusalCode`. Первая
 * редакция принимала результат `safeRefusal` — то есть строку, в выборе которой участвовал
 * текст портала, а в тексте портала едет процитированный ответ клиента. Респондент,
 * набравший в анкете `expired_token`, объявлял бы грант своего портала мёртвым.
 * Теперь решение принимается по полю `error` ответа портала и ни по чему больше.
 */
export function isDeadGrant(error: unknown): boolean {
  return DEAD_GRANT_CODES.includes(refusalCode(error))
}

/**
 * Сколько ждём, прежде чем стереть.
 *
 * ⚠ Отсрочка обязательна, и она не про осторожность, а про обратимость. Отказ может быть
 * и не про уход клиента: портал переносили, сеть моргнула, у нас разъехался ключ шифрования.
 * Стерев токены сразу, мы заставили бы клиента переустанавливать приложение из-за суточного
 * перерыва — а стереть можно только один раз.
 *
 * Тридцать суток: рабочее значение у соседа (`client-bank-alfa-by`), а не его нижний порог
 * в четырнадцать. Первая редакция брала четырнадцать, и панель ревью PR #34 указала, что
 * это пол, ниже которого сосед запрещает настраивать, а не то, с чем он живёт. Пока живых
 * данных о ложных срабатываниях у нас нет, брать чужой минимум вместо чужого рабочего
 * значения — выбор в пользу необратимой стороны.
 */
export const PURGE_GRACE_DAYS = 30

const DAY_MS = 24 * 60 * 60 * 1000

/**
 * Граница: всё, что помечено РАНЬШЕ неё, пора стирать.
 *
 * Считает вызывающий и передаёт в запрос готовым значением — SQL не должен знать про политику,
 * а тест не должен подсовывать часы в базу. Строгое «раньше» на стороне SQL: отметка ровно
 * на границе оставляет портал в живых ещё на тик, и это правильная сторона ошибки.
 */
export function purgeBoundary(now: Date, graceDays: number = PURGE_GRACE_DAYS): Date {
  return new Date(now.getTime() - graceDays * DAY_MS)
}

/**
 * Исход обустройства → статус портала.
 *
 * ⚠ Существует потому, что вызывающих стало ТРОЕ: установка, кнопка «доустроить» в мастере
 * и фоновое долечивание. До этого запись статуса была только у установки, и кнопка
 * «доустроить» оставляла портал в `degraded` даже после успеха — то есть чинила портал
 * и не признавала этого. Найдено при разборе issue #12.
 *
 * Четыре исхода сводятся к двум статусам намеренно. `not-admin`, `no-scope` и `failed`
 * лечатся по-разному и по-разному объясняются человеку, но для нас все три означают одно:
 * приложение стоит и не работает. Заводить отдельный статус под каждый значило бы завести
 * второй источник правды рядом с самим исходом.
 */
export function statusAfterProvision(outcome: 'ok' | 'not-admin' | 'no-scope' | 'failed'): 'active' | 'degraded' {
  return outcome === 'ok' ? 'active' : 'degraded'
}

/**
 * Сколько минут портал может числиться обустраиваемым, прежде чем считать это зависанием.
 *
 * Бюджет всей цепочки обустройства — 45 секунд (`PROVISION_BUDGET_MS`), то есть десять минут
 * это двенадцатикратный запас. Больше означает не «долго идёт», а «процесс умер между
 * захватом портала и записью исхода»: контейнер перезапустили, машину выключили.
 *
 * ⚠ Без возврата такой портал застрял бы в `provisioning` навсегда — и это ровно тот же
 * дефект, ради которого у буфера ответов появился `requeueStuck`: статус «взят в работу»
 * без срока превращается в статус «потерян».
 */
export const PROVISION_STUCK_MINUTES = 10

/** Граница: всё, что взято в работу РАНЬШЕ неё, считаем брошенным. */
export function stuckProvisioningBoundary(now: Date, minutes: number = PROVISION_STUCK_MINUTES): Date {
  return new Date(now.getTime() - minutes * 60 * 1000)
}
