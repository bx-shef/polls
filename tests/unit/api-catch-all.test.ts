import { describe, expect, it } from 'vitest'
import handler from '../../server/api/[...]'

/**
 * Гвард под дефект, пойманный на боевом домене: `GET /api/чего-нет` отвечал **200
 * и HTML-страницей** — обработчика нет, запрос проваливался в SPA-правило `/**`.
 *
 * Для приложения Битрикс24 это дорого: адрес обработчика событий вписывается в карточку
 * приложения руками, и опечатка выглядела бы как исправный обработчик — портал видит 200
 * и считает событие доставленным.
 *
 * Я утверждал в трёх местах, что роут Nitro нельзя импортировать в тест, и оправдывал этим
 * отсутствие проверок. Ревью это опровергло. Роут импортируется обычным образом, потому что
 * помощники в нём импортированы явно, а не взяты автоимпортом.
 */

describe('несуществующий путь под /api/', () => {
  const call = (path: string) => (handler as unknown as (event: { path: string }) => unknown)({ path })

  it('отвечает 404, а не 200 страницей', () => {
    expect(() => call('/api/definitely-not-here')).toThrowError(
      expect.objectContaining({ statusCode: 404 }),
    )
  })

  it('отдаёт путь в данных ошибки, чтобы опечатку было видно', () => {
    try {
      call('/api/instal')
      expect.unreachable('обработчик обязан бросить')
    }
    catch (error) {
      expect((error as { data?: unknown }).data).toEqual({ path: '/api/instal' })
    }
  })
})
