import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

/**
 * Проверки ИСХОДНИКА лендинга, а не отрендеренного DOM.
 *
 * Живут отдельно от `tests/nuxt/index-page.test.ts` по двум причинам. Первая техническая:
 * в окружении Nuxt `import.meta.url` не файловый, и чтение с диска там невозможно. Вторая
 * важнее: то, что здесь проверяется, в отрендеренный DOM не попадает в принципе — именно
 * поэтому обе проверки в прошлой редакции были тавтологиями.
 */

const SOURCE = readFileSync(new URL('../../app/pages/index.vue', import.meta.url), 'utf8')

describe('исходник лендинга', () => {
  it('не строит разметку из внешних источников', () => {
    // ⚠ Первая редакция искала строку `v-html` в `p.html()` смонтированной страницы, и это
    // не могло провалиться никогда: компилятор Vue превращает директиву в присваивание
    // `innerHTML`, так что её имя в выводе не появляется. Тест был зелёным и при живом
    // `v-html` с чужим текстом. Нашла панель ревью PR #28, проверяющий подтвердил это
    // зондом с настоящей директивой.
    expect(SOURCE).not.toMatch(/v-html/)
    expect(SOURCE).not.toMatch(/innerHTML/)
  })

  it('не ведёт на страницы, которых нет', () => {
    // ⚠ Гвард под находку панели ревью PR #28: в подвале стояли ссылки на `/eula`
    // и `/privacy-policy`, а юридического пакета в проекте нет — две мёртвые ссылки
    // на единственной индексируемой странице продукта, которую читает и модератор Маркета.
    //
    // Список путей записан здесь вручную, а не выведен из роутера: выведенный из роутера,
    // он подтверждал бы сам себя — появись в проекте пустая страница `/eula`, тест
    // позеленел бы, ничего не проверив.
    const pages = ['/', '/app', '/install', '/portal/deal-tab', '/help']

    for (const [, href] of SOURCE.matchAll(/<a[^>]+href="([^"]+)"/g)) {
      if (href === undefined || !href.startsWith('/')) continue
      expect(pages, `ссылка ${href} ведёт на несуществующую страницу`).toContain(href)
    }
  })

  it('не задаёт цвета значениями', () => {
    // Правило проекта: цвет задаётся именем роли, а не значением, и обе темы обязательны.
    // Лендинг завёл было собственный набор из восемнадцати литералов, и они разъехались
    // с общими ещё до мержа. Нашла панель ревью PR #28.
    // Комментарии вырезаем: в них литералы законны и нужны — объяснение, почему так больше
    // не делают, без исходных значений не объяснение. Ищем только то, что дойдёт до браузера.
    const style = SOURCE.slice(SOURCE.indexOf('<style')).replace(/\/\*[\s\S]*?\*\//g, '')
    const literals = [...style.matchAll(/#[0-9a-f]{3,8}\b/gi)].map(match => match[0])

    expect(literals, `в стилях лендинга остались литеральные цвета: ${literals.join(', ')}`).toEqual([])
  })
})
