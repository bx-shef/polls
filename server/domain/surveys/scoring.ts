import type { SurveyBand, SurveySection, SurveyTemplate } from './model'
import type { AnswerValue } from './answer'

/**
 * Turns answers into section scores.
 *
 * Чистая функция: шаблон и ответы на входе, баллы на выходе. Ни базы, ни портала — поэтому
 * проверяется вызовом, и проверять её надо много: это единственное место, где ответ человека
 * превращается в число, по которому потом принимают решения.
 *
 * Формула взята у источника (`legacy/LEGACY-ANALYSIS.md`, `Item::calcStructData`): по секции
 * суммируется `значение × вес / 100` по балльным вопросам, результат округляется до двух знаков.
 * Веса во всех двенадцати анкетах дают ровно 100, шкала у всех балльных вопросов 0–10 — то есть
 * балл секции это взвешенное среднее в шкале 0–10.
 *
 * ⚠ Одно отличие от источника, и оно принципиальное: **пропуск не считается нулём.** В старом
 * решении пропустить было нельзя — ползунок всегда имел значение, — поэтому формула с `null`
 * не встречалась. У нас «не ответил» это `null` по инварианту проекта, и включить его в сумму
 * как ноль значило бы объявить молчание худшей возможной оценкой. Поэтому неотвеченные вопросы
 * выбрасываются И из суммы, И из делителя: балл считается по тому, на что ответили.
 *
 * На полностью заполненной анкете с весами в сумме 100 это даёт ровно ту же цифру, что и старая
 * формула, — иначе сверка баллов в задаче 6 была бы невозможна.
 */

/** Балл одной секции и то, из чего он сложился. */
export interface SectionScore {
  key: string
  title: string
  /**
   * Балл секции в её шкале, округлённый до двух знаков.
   *
   * `null` означает «балла нет», и причин у этого две: секция не даёт балла вовсе
   * (секция открытых вопросов) либо в ней не ответили ни на один балльный вопрос.
   * Ноль такой же честный балл, как десятка, и путать его с отсутствием нельзя.
   */
  score: number | null
  /** На сколько балльных вопросов секции ответили. */
  answered: number
  /** Сколько балльных вопросов в секции идёт в оценку. */
  scored: number
  /** Диапазон интерпретации, в который попал балл: текст для респондента. */
  band: SurveyBand | null
}

export interface SurveyScore {
  sections: SectionScore[]
  /**
   * Общий балл — среднее по секциям, у которых балл есть.
   *
   * Именно среднее ПО СЕКЦИЯМ, а не взвешенное по всем вопросам сразу: секции у клиента
   * называются «Продукт», «Процессы», «Персонал» и читаются как три равноправные стороны
   * работы. Взвешивание по числу вопросов сделало бы вес стороны следствием того, сколько
   * про неё придумали спросить, — а это случайность конструктора, а не замысел.
   *
   * ⚠ Числа этого не было в старом решении: там три балла по секциям и никакого итога.
   * Заводим его ровно под две вещи, которым нужна ОДНА цифра: фильтры и роботы клиента
   * на стороне портала и порог тревоги. Главной метрикой отчёта он не выносится — это
   * инвариант проекта, и отчёт показывает доли по корзинам.
   */
  overall: number | null
}

/**
 * Посчитать баллы по всем секциям шаблона.
 *
 * Ответы приходят уже проверенными (`checkAnswers`): лишних ключей в них нет, значения
 * в шкале, пропуск выражен `null`. Здесь ещё раз это не проверяется — двойная проверка
 * расходится с оригиналом ровно тогда, когда правят одну из двух.
 */
export function scoreSurvey(template: SurveyTemplate, answers: Record<string, AnswerValue>): SurveyScore {
  const sections = template.sections.map(section => scoreSection(section, answers))

  const scored = sections.map(s => s.score).filter((s): s is number => s !== null)
  return {
    sections,
    overall: scored.length === 0 ? null : round2(scored.reduce((sum, s) => sum + s, 0) / scored.length),
  }
}

function scoreSection(section: SurveySection, answers: Record<string, AnswerValue>): SectionScore {
  // Балл дают только балльные вопросы, и только те, что помечены идущими в оценку.
  // В источнике выключение выражалось весом 0 — неотличимо от опечатки; у нас это флаг.
  const scoring = section.questions.filter(q => q.scored && q.type === 'scale')

  let weighted = 0
  let weight = 0
  let answered = 0

  for (const question of scoring) {
    const value = answers[question.key]
    // ⚠ Только числа. `null` — пропуск, и он не участвует ни в сумме, ни в делителе.
    // Строка сюда попасть не должна, но если попадёт — это не повод считать её нулём.
    if (typeof value !== 'number') continue

    weighted += value * question.weight
    weight += question.weight
    answered += 1
  }

  const score = !section.scored || weight === 0 ? null : round2(weighted / weight)

  return {
    key: section.key,
    title: section.title,
    score,
    answered,
    scored: scoring.length,
    band: score === null ? null : findBand(section.bands, score),
  }
}

/**
 * Найти диапазон интерпретации для балла.
 *
 * ⚠ Границы ВКЛЮЧИТЕЛЬНЫЕ с обеих сторон, а в источнике диапазоны смежные (…6–7.5, 7.5–8…).
 * Значит ровно на стыке подходят оба, и побеждает первый по порядку. Это выбор, а не
 * недосмотр: альтернатива — полуинтервалы, но тогда балл, равный верхней границе последнего
 * диапазона, не попадёт никуда, и клиент с оценкой 10 не увидит текста вовсе.
 *
 * `null` — балл не покрыт ни одним диапазоном. Такое бывает и это не ошибка расчёта:
 * в источнике диапазоны были заполнены у одной анкеты из двенадцати, а ниже четвёрки
 * не покрывалось ничем. Адаптер импорта на такие дыры ругается отдельно.
 */
export function findBand(bands: readonly SurveyBand[], score: number): SurveyBand | null {
  return bands.find(band => score >= band.from && score <= band.to) ?? null
}

/**
 * Округление до двух знаков — как в источнике.
 *
 * ⚠ Округляем ОДИН раз, в самом конце. Округление промежуточных сумм копит ошибку, и балл
 * разошёлся бы с историческим на сотые — ровно на той величине, на которой сверка в задаче 6
 * и должна сойтись.
 *
 * `Number(x.toFixed(2))`, а не `Math.round(x * 100) / 100`: второе на значениях вроде
 * `1.005` даёт 1 вместо 1.01, потому что умножение на 100 уже приносит двоичную погрешность.
 */
function round2(value: number): number {
  return Number(value.toFixed(2))
}
